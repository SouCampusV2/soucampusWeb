// Мягкое свечение акцентом в верхней части страницы (hero-подсветка).
//
// ЕДИНСТВЕННЫЙ способ сделать это свечение на сайте. Раньше половина
// страниц носила копию градиента прямо в классах, и копии разъехались:
// пять разных высот (772/676/640/512px), два отступа сверху, два разных
// рецепта градиента и два способа задать ширину. Поэтому наружу торчит
// ровно один проп — цвет. Вся геометрия ниже, в константах: чтобы
// поменять её, есть одно место, и разъехаться копиям физически негде.
//
// ГЕОМЕТРИЯ — ПОЧЕМУ ИМЕННО ТАК (четыре разных бага, 2026-07-27):
//
// 1. Свечение обрывалось видимой ГОРИЗОНТАЛЬНОЙ линией снизу. Причина —
//    не размер блока, а `radial-gradient(circle …)`: круг по умолчанию
//    размера farthest-corner, то есть его радиус ≈ sqrt((w/2)² + h²). На
//    широком экране это заметно БОЛЬШЕ высоты блока, поэтому у нижнего
//    края градиент ещё цветной — и край блока виден как ровный срез.
//    Лечится явным размером: `ellipse 60% 100%` привязывает радиусы к
//    самому блоку (rx = 0.6·ширины, ry = высота), а стоп `transparent
//    70%` тогда наступает на 0.42·ширины по горизонтали (< половины
//    ширины) и на 0.7·высоты по вертикали (< высоты) — прозрачность
//    достигается ВНУТРИ блока, до его краёв. Резать нечего.
//
// 2. Свечение обрывалось ВЕРТИКАЛЬНОЙ линией справа. Причина — `w-full`
//    мерялся по контентной ширине родителя (за вычетом его паддингов, у
//    магазина это до 120px с каждой стороны). Отсюда `w-screen`: ширина
//    берётся от окна и от родителя больше не зависит вообще.
//
// 3. Свечение обрывалось линией СВЕРХУ. Центр градиента стоит на верхней
//    грани блока (`at 50% 0%`), то есть эта грань — самое яркое место, и
//    любой её выход в видимую область читается как срез. Значит блок
//    обязан начинаться ВЫШЕ верха документа: -top-40 (160px) с запасом
//    перекрывает ~82px, которые навбар резервирует в потоке.
//
// 4. Свечение обрывалось ДВУМЯ вертикальными линиями симметрично. Клип и
//    ограничение ширины стояли на ОДНОМ элементе (`max-w-6xl … overflow-
//    x-clip`), и контейнер честно отсекал всё, что за него вылезло, —
//    включая наше свечение.
//
// ТРЕБОВАНИЕ К РОДИТЕЛЮ (следствие пунктов 2 и 4). Родитель обязан быть
// `relative`, ПОЛНОШИРИННЫМ и нести `overflow-x-clip`; ограничение
// ширины (`max-w-*`) живёт строго на контенте ВНУТРИ него, не на самом
// родителе. Клип нужен из-за `w-screen`: 100vw не вычитает вертикальный
// скроллбар, и без клипа страница получает горизонтальный скролл.

/** Высота блока свечения. Эталон — hero лендинга, самая проработанная
 *  страница; остальные подтянуты к нему. Меняется здесь для всего сайта. */
const HEIGHT = "h-[48rem]";

/** Насколько блок задран выше верха документа (пункт 3). */
const OFFSET_TOP = "-top-40";

/** Потолок ширины: до 90rem свечение тянется за окном, дальше замирает.
 *  Без потолка на ультрашироком мониторе пятно расползается в блёклую
 *  полосу — `ellipse 60%` считается от ширины блока, а она была бы 2560px. */
const WIDTH = "w-screen max-w-[90rem]";

export function PageGlow({
  color,
}: {
  /** Цвет ядра свечения, готовая rgba-строка: "rgba(251,146,60,0.35)". */
  color: string;
}) {
  return (
    <div
      aria-hidden
      // Цвет приходит пропом, поэтому градиент — инлайновый style, а не
      // класс: Tailwind собирает классы статическим разбором исходников и
      // подставленную в рантайме строку просто не увидит.
      style={{
        backgroundImage: `radial-gradient(ellipse 60% 100% at 50% 0%, ${color}, transparent 70%)`,
      }}
      className={`pointer-events-none absolute left-1/2 -z-10 -translate-x-1/2 ${OFFSET_TOP} ${HEIGHT} ${WIDTH}`}
    />
  );
}
