"use client";

import { useSearchParams } from "next/navigation";
import { BackLink } from "@/components/BackLink";

// Ссылка «назад» на странице работы — единственное место, которому нужен
// адресный параметр `?from=home` (2026-09-11).
//
// ------------------------------------------------------------
// Зачем понадобился отдельный компонент
// ------------------------------------------------------------
// Карточки ведут сюда с двух экранов — с главной (RecentProjects) и из
// каталога работ, — и возвращать человека надо туда, откуда он пришёл.
// Откуда именно, говорит `?from=home`; router.back() не годится, потому
// что ссылкой делятся и открывают с нуля.
//
// Читала параметр сама страница, через проп `searchParams`. И вот цена
// этой одной строки: **страница, объявившая searchParams, перестаёт быть
// статической**. Параметры адреса известны только в момент запроса,
// значит Next обязан рендерить её на каждый заход — при том, что всё
// остальное на ней (текст, фото, размеры) заранее известно и не меняется.
// В выводе сборки это видно буквой: `ƒ` вместо `●`. Шестнадцать работ
// собирались заново каждому посетителю ради одного слова в ссылке.
//
// ------------------------------------------------------------
// Почему именно так лечится
// ------------------------------------------------------------
// Знание об адресе спускается на уровень ниже — в клиентский компонент,
// где `useSearchParams()` читает строку запроса уже в браузере. Страница
// про параметр больше не знает и возвращается в статику.
//
// ⚠️ `<Suspense>` вокруг — обязателен, и не как украшение. Без него
// `useSearchParams()` заставляет Next отрисовать на клиенте ВСЁ дерево
// страницы (bailout), то есть проблема просто переезжает на уровень
// выше. Граница Suspense говорит: «вот отсюда и ниже значение приедет
// позже, остальное отдавай статикой». Ставит её страница — сюда её
// убрать нельзя, граница обязана быть СНАРУЖИ компонента, который
// приостанавливается.
//
// ⚠️ Запасной вариант (fallback) — не пустота и не скелет, а **готовая
// ссылка на каталог**. Три довода, и каждый про честность разметки:
//   1. это верный ответ для большинства: без `?from=home` ссылка ведёт
//      в каталог, а параметра нет ни у поисковика, ни у того, кому
//      кинули ссылку в Discord;
//   2. в серверном HTML оказывается настоящая рабочая ссылка, а не
//      заглушка — это и есть то, за что боролись на витрине 07.09,
//      когда каталога не было в HTML вовсе;
//   3. подмена происходит ровно в одном случае — пришёл с главной, — и
//      меняется в ней только надпись.
//
// ------------------------------------------------------------
// Куда именно «назад» (2026-09-24)
// ------------------------------------------------------------
// Не в начало экрана, а к карточке ЭТОЙ работы: `#work-<slug>` в каталоге
// и `#home-work-<slug>` на главной. Карточки носят эти id, и прокручивает
// к ним сам Next. До 24.09 любой переход с якорем всё равно приезжал на
// верх — PageTransition затирал прокрутку (разбор в его эффекте).
//
// Исключение — работы из hero-карусели /portfolio: они и есть верх
// страницы, а id на панели карусели заставил бы браузер сдвигать её
// overflow вбок (тот же довод, что у отзывов в ClientReviews).
type Target = { slug: string; featured: boolean };

export function PortfolioBackLink(target: Target) {
  const from = useSearchParams().get("from");
  return from === "home" ? (
    <BackLink href={`/#home-work-${target.slug}`}>Home</BackLink>
  ) : (
    <PortfolioBackLinkFallback {...target} />
  );
}

/**
 * То, что уходит в серверный HTML и стоит на месте до гидратации.
 *
 * Отдельным экспортом, а не копией разметки на странице: два места,
 * рисующие одну ссылку, однажды разъедутся — ровно эту болезнь лечил
 * общий BackLink, когда таких ссылок было пять.
 */
export function PortfolioBackLinkFallback({ slug, featured }: Target) {
  return (
    <BackLink href={featured ? "/portfolio" : `/portfolio#work-${slug}`}>
      All work
    </BackLink>
  );
}
