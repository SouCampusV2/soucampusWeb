"use client";

import { useCallback, useTransition } from "react";
import { useRouter } from "next/navigation";
import { useNotificationEvents } from "@/lib/useNotificationEvents";

// Ничего не рисует — перечитывает страницу, когда база сказала, что
// пришло новое уведомление.
//
// Почему так, а не «дорисовать строку на клиенте по данным из события»:
// список рендерит сервер, и он же решает, как уведомление выглядит —
// иконка вида, формат даты, безопасная ссылка. Собирать вторую, клиентскую
// версию того же списка значило бы завести второй источник правды о том,
// как выглядит уведомление, и однажды они разъедутся. router.refresh()
// перезапрашивает серверную разметку и подменяет её на месте: прокрутка,
// фокус и состояние клиентских компонентов остаются.
//
// Это ровно то, что делает кнопка «обновить» рядом, — только нажимает её
// теперь база. Кнопку не убираем: соединение может отвалиться (спящий
// ноутбук, метро, прокси, режущий WebSocket), и тогда нужен способ
// спросить руками.
export function NotificationsLive({ userId }: { userId: string }) {
  const router = useRouter();
  const [, startTransition] = useTransition();

  // startTransition обязателен, и это выяснилось опытом, а не из
  // документации: ровно тот же router.refresh() из кнопки «обновить»
  // рядом работал, а отсюда — нет. Разница была одна. Кнопку нажимает
  // человек, то есть вызов идёт изнутри обработчика события React, где
  // обновление и так попадает в правильную очередь. А сюда вызов
  // приходит из колбэка WebSocket — снаружи React вообще, и без явного
  // перехода перерисовка серверной части не доезжала.
  const refresh = useCallback(
    () => startTransition(() => router.refresh()),
    [router]
  );

  // Только INSERT. UPDATE здесь — это почти всегда «прочитано», отметку
  // ставит сам этот экран, и перечитывать страницу в ответ на собственное
  // же действие значит гонять сервер по кругу.
  useNotificationEvents(userId, refresh);

  return null;
}
