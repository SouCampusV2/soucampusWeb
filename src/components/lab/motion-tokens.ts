"use client";

import { useReducedMotion } from "motion/react";

// Токены движения для лаборатории лендинга (2026-09-21).
//
// Взяты из привезённого скилла `motion-system` и переведены в наши
// числа. Смысл системы не в красоте кривых, а в том, что длительность и
// easing перестают выбираться на глаз в каждом компоненте: в проекте это
// уже проходили с градиентом (семь копий) и с датами (семь форматов).
//
// ⚠️ ЭТО ЛАБОРАТОРИЯ, А НЕ ДИЗАЙН-СИСТЕМА САЙТА. Пока файл живёт в
// `src/components/lab/` и применяется только на /lab. Если владелец
// выберет вариант, токены переезжают в `docs/DESIGN.md` и в общий код —
// отдельным решением, а не по дороге.
//
// Существующая анимация перехода между страницами (PageTransition) под
// эти токены НЕ подгонялась: у неё свои константы, заказанные владельцем,
// и трогать их ради лаборатории нельзя.

/** Длительности в секундах — Motion принимает секунды, не миллисекунды. */
export const DURATION = {
  /** Мгновенно: переключатели, состояния кнопок. */
  instant: 0.05,
  /** Мелочь: подсказка, чип. */
  fast: 0.1,
  /** По умолчанию почти для всего. */
  normal: 0.2,
  /** Средние блоки: панель, карточка. */
  moderate: 0.3,
  /** Появление секции при скролле. */
  slow: 0.4,
  /** Осознанно медленный акцент: первый экран. */
  deliberate: 0.6,
} as const;

/**
 * Кривые. Имена — по смыслу, а не по форме: «входит», «уходит», а не
 * «easeOutQuad». Иначе выбор снова становится вкусовым.
 */
export const EASE = {
  /** Большинство переходов между состояниями. */
  standard: [0.2, 0, 0, 1],
  /** Появление на экране — торможение в конце. */
  decelerate: [0, 0, 0.2, 1],
  /** Уход с экрана — разгон. */
  accelerate: [0.3, 0, 1, 0.3],
  /** Тактильное, с лёгким перелётом. Только там, где это уместно. */
  spring: [0.34, 1.56, 0.64, 1],
} as const;

/**
 * Шаг лестницы для группы элементов. 40мс — середина рекомендованного
 * диапазона 30–50.
 *
 * ⚠️ Потолок всей последовательности — 500мс. Значит длинную сетку
 * карточек нельзя выстраивать по одной: на двенадцати карточках шаг в
 * 40мс даёт почти полсекунды только на задержки. Поэтому ниже есть
 * `staggerIndex` с ограничением.
 */
export const STAGGER = 0.04;

/** Максимум элементов, которые ещё имеет смысл выстраивать лесенкой. */
const STAGGER_CAP = 8;

/**
 * Задержка для i-го элемента группы. Дальше STAGGER_CAP задержка не
 * растёт — иначе последняя карточка появлялась бы через секунду после
 * первой, и это читалось бы не как ритм, а как тормоза.
 */
export function staggerIndex(index: number): number {
  return Math.min(index, STAGGER_CAP) * STAGGER;
}

/**
 * Настройки появления при скролле — одни на всю лабораторию.
 *
 * ⚠️ `prefers-reduced-motion` обрабатывается ЗДЕСЬ, а не в каждом
 * компоненте. Правило из скилла, и оно верное: обработка «по месту»
 * означает, что однажды её где-то забудут, а заметить это может только
 * тот, кому от движения плохо.
 *
 * При выключенном движении остаётся прозрачность: она считается
 * приемлемой и сохраняет ощущение, что блок появился, без сдвигов.
 */
export function useReveal() {
  const reduced = useReducedMotion();

  return function reveal(index = 0, distance = 16) {
    if (reduced) {
      return {
        initial: { opacity: 0 },
        whileInView: { opacity: 1 },
        viewport: { once: true, margin: "-80px" },
        transition: { duration: DURATION.normal, delay: 0 },
      } as const;
    }

    return {
      initial: { opacity: 0, y: distance },
      whileInView: { opacity: 1, y: 0 },
      viewport: { once: true, margin: "-80px" },
      transition: {
        duration: DURATION.slow,
        delay: staggerIndex(index),
        ease: EASE.decelerate,
      },
    } as const;
  };
}
