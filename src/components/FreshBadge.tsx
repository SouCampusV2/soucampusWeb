"use client";

import { useCallback, useSyncExternalStore } from "react";
import { isFreshPurchase, FRESH_PURCHASE_MS } from "@/lib/orders";

// Бейдж «NEW» на только что купленной карте (решение владельца
// 2026-08-26: заказ моложе двух минут).
//
// ПОЧЕМУ КЛИЕНТСКИЙ, а не пара строк на серверной странице. «Сейчас» —
// это состояние браузера, такое же, как часовой пояс у LocalTime или
// содержимое корзины у AddToCartButton. Сервер собирает страницу один
// раз и знает только своё время; React запрещает звать Date.now() в
// рендере ровно по этой причине — результат меняется сам, а разметка
// обязана быть предсказуемой.
//
// ПОЧЕМУ useSyncExternalStore, а не useState + useEffect. Второе — это
// setState внутри эффекта, то есть лишний рендер и правило, которое
// проект уже обходил дважды (useHydrated.ts, PortfolioHero). Здесь
// «свежесть» и правда внешний источник: она зависит от часов, а не от
// наших действий, и меняется сама.
//
// Три части стора:
//   subscribe — будильник на остаток срока: у каждой строки он свой,
//               общий тик раз в секунду будил бы весь список зря;
//   snapshot  — ответ на «свежая ли она ПРЯМО сейчас»;
//   server    — false: на сервере бейджа нет вовсе. Первый клиентский
//               кадр обязан совпасть с серверным HTML дословно, иначе
//               рушится гидратация (та самая ошибка #418, что стоила
//               проекту полдня на датах).
//
// ⚠️ И это снимает известную оговорку: бейдж ГАСНЕТ САМ. В IDEAS.md
// стояло «через три минуты человек будет видеть NEW до перезагрузки,
// лечится клиентским таймером либо ничем». Раз компонент всё равно
// клиентский, будильник стоит три строки — и висящий бейдж, который
// врёт про «только что», перестал существовать.
export function FreshBadge({ purchasedAt }: { purchasedAt: string }) {
  const subscribe = useCallback(
    (onChange: () => void) => {
      const left = FRESH_PURCHASE_MS - (Date.now() - Date.parse(purchasedAt));
      // Старая покупка — будить некого, бейджа и так нет.
      if (!(left > 0)) return () => {};
      const timer = setTimeout(onChange, left);
      return () => clearTimeout(timer);
    },
    [purchasedAt]
  );

  const fresh = useSyncExternalStore(
    subscribe,
    () => isFreshPurchase(purchasedAt, Date.now()),
    () => false
  );

  if (!fresh) return null;

  // Бейдж, а не заливка карточки: bg-orange-50 по всему сайту занят под
  // предупреждения (причина снятия карты, заметка на загрузке), и
  // красить им «хорошее» значило бы отобрать у оранжевой плашки её
  // единственный смысл — «обрати внимание, что-то не так».
  //
  // Цветная поверхность, поэтому без dark:-варианта: по DESIGN.md чипы и
  // бейджи не инвертируются — они одинаково читаются на любом фоне.
  return (
    <span className="shrink-0 rounded-full bg-orange-400 px-2 py-0.5 text-[11px] font-bold uppercase tracking-wide text-zinc-950">
      New
    </span>
  );
}
