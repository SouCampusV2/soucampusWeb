"use client";

import { useHydrated } from "@/lib/useHydrated";
import { formatLocal, formatUtc, type DateShape } from "@/lib/dates";

// Момент времени, показанный в поясе ЧИТАТЕЛЯ (решение владельца
// 2026-08-22).
//
// ПОЧЕМУ ЭТО КОМПОНЕНТ, А НЕ ФУНКЦИЯ. Функцию нельзя позвать в разметке
// напрямую: страницы собираются на сервере (Vercel, UTC), а читатель
// живёт в своём поясе. Сервер отдал бы «19:03», браузер на первом же
// рендере посчитал бы «22:03», React сверил бы два текста посимвольно и
// уронил гидратацию — ошибка #418, разобранная в шапке lib/dates.ts и
// стоившая проекту полдня на уведомлениях.
//
// Поэтому здесь два кадра, и первый из них НАМЕРЕННО «неправильный»:
//
//   до гидратации — UTC, ровно то же, что в серверном HTML → React
//                   доволен, поддерево не перерисовывается;
//   после         — пояс читателя.
//
// Тот же приём и та же причина, что у AddToCartButton (корзина в
// localStorage) и ReactionButton (кто нажал): показать состояние
// браузера можно только ПОСЛЕ гидратации.
//
// ⚠️ ЧТО ЭТО ЗНАЧИТ НА ГЛАЗ. У читателя западнее или восточнее Гринвича
// час на мгновение сменится сам. Это заметно и это цена. Альтернатива —
// динамический рендер страницы товара на каждого посетителя, то есть
// отказ от статики ради часа в подписи. Не стоит того.
//
// ⚠️ ЧТО СЮДА НЕ ПЕРЕДАВАТЬ: дни-ключи вида «2026-08-14» (столбики
// графика продаж, границы периода). Это не момент, а название суток,
// посчитанное в базе по UTC, и пересчёт в чужой пояс сдвинет подпись на
// сутки. Для них есть formatDate/formatDayMonth — с пришпиленным UTC.
// Разбор — большой блок в шапке lib/dates.ts.

export function LocalTime({
  value,
  shape = "dayMonthYear",
  className,
}: {
  /** ISO-момент из базы (timestamptz), а НЕ день-ключ «2026-08-14». */
  value: string | Date;
  shape?: DateShape;
  className?: string;
}) {
  const hydrated = useHydrated();
  const iso = new Date(value).toISOString();

  return (
    // <time> — не украшение: машиночитаемая дата в dateTime остаётся
    // верной независимо от того, какой из двух кадров сейчас на экране.
    // title даёт полный момент по наведению, включая час, даже когда
    // форма его не показывает.
    <time dateTime={iso} title={formatUtc(value, "dayMonthYearTime") + " UTC"} className={className}>
      {hydrated ? formatLocal(value, shape) : formatUtc(value, shape)}
    </time>
  );
}
