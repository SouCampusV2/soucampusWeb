import type { Product } from "@/lib/products";

// Подбор похожих карт под страницей товара.
//
// ЗАДАЧА СФОРМУЛИРОВАНА ВЛАДЕЛЬЦЕМ ТАК: «чтобы реально были схожие
// варианты, а не просто рандом». Отсюда всё устройство ниже, и главное в
// нём — не формула, а последнее правило: если похожих нет, блок не
// показывается ВООБЩЕ. Добить подборку случайными картами до красивых
// четырёх штук — ровно то, что просили не делать: посетитель не отличит
// «мы подобрали» от «мы насыпали», а доверие тратится один раз.
//
// ПОЧЕМУ СЧИТАЕМ ЗДЕСЬ, А НЕ В БАЗЕ. Функция в Postgres была бы быстрее
// на большом каталоге, но:
//   1. Страница товара СТАТИЧЕСКАЯ — подборка считается на сборке, а не
//      на каждого посетителя. То есть цена платится один раз.
//   2. Чистая функция проверяется тестами, а SQL-функция — только живой
//      базой. В проекте тестами закрыты именно такие вещи (pricing,
//      projects, dates), и это единственный способ поймать, что формулу
//      сломали правкой.
//   3. Каталог сейчас — десять карт.
//
// ⚠️ КОГДА ПЕРЕЕЗЖАТЬ В БАЗУ: когда карт станет заметно больше сотни.
// Тогда «прочитать весь каталог, чтобы показать четыре карточки»
// перестанет быть бесплатным даже на сборке. Порог и замеры — те же, что
// у остального каталога, docs/ARCHITECTURE.md § 7.1.

/**
 * Вес каждого совпадения. Числа не подобраны наугад — они выражают, что
 * СИЛЬНЕЕ говорит о схожести.
 *
 * Категория и тип весят больше всего: это ответ на вопрос «что это
 * вообще такое». Спавн похож на спавн, а не на интерьер, даже если у них
 * общий тег.
 *
 * Версия Minecraft весит меньше всех и ограничена сверху: её пишут почти
 * одинаково у всех карт (сегодня это 1.21), поэтому совпадение по ней
 * почти ничего не сообщает. Без потолка «все карты под 1.21» оказались бы
 * похожи друг на друга — то есть подборка выродилась бы в тот самый
 * рандом.
 */
const WEIGHTS = {
  category: 5,
  mapType: 4,
  theme: 3,
  tag: 2,
  gameMode: 1,
  mcVersion: 1,
  sameCreator: 2,
} as const;

/**
 * Потолки на списочные совпадения. Одна карта может нести двадцать тегов,
 * и без ограничения она перевесила бы всё остальное просто своей
 * многословностью — то есть подборку определял бы не смысл, а то, кто
 * подробнее заполнил форму.
 */
const CAPS = {
  theme: 6,
  tag: 6,
  gameMode: 3,
  mcVersion: 2,
} as const;

/**
 * Ниже этого порога карта считается НЕ похожей и в подборку не идёт.
 *
 * Тройка выбрана так, чтобы одного слабого совпадения не хватало: общий
 * тег (2) или общие версии Minecraft (максимум 2) сами по себе порога не
 * берут, а общая тема (3) или общая категория (5) — берут.
 */
const MIN_SCORE = 3;

/** Сколько совпадений в двух списках, без учёта регистра и порядка. */
function overlap(a: string[], b: string[]): number {
  if (a.length === 0 || b.length === 0) return 0;
  const set = new Set(b.map((v) => v.toLowerCase()));
  let n = 0;
  for (const value of a) {
    if (set.has(value.toLowerCase())) n += 1;
  }
  return n;
}

/**
 * Насколько `other` похожа на `base`. Ноль — не похожа вовсе.
 *
 * Мера СИММЕТРИЧНА: score(a, b) === score(b, a). Это не украшение —
 * несимметричная мера означала бы, что карта A попадает в подборку к B, а
 * B к A не попадает, и объяснить такое посетителю нечем.
 */
export function similarityScore(base: Product, other: Product): number {
  let score = 0;

  if (base.category === other.category) score += WEIGHTS.category;

  // Пустое поле не совпадает с пустым: две карты, у которых тип не
  // заполнен, не становятся от этого похожими. Иначе все карты, залитые
  // до миграции с характеристиками, слиплись бы в одну кучу.
  if (
    base.specs.mapType &&
    other.specs.mapType &&
    base.specs.mapType.toLowerCase() === other.specs.mapType.toLowerCase()
  ) {
    score += WEIGHTS.mapType;
  }

  score += Math.min(
    overlap(base.specs.themes, other.specs.themes) * WEIGHTS.theme,
    CAPS.theme
  );
  score += Math.min(
    overlap(base.specs.tags, other.specs.tags) * WEIGHTS.tag,
    CAPS.tag
  );
  score += Math.min(
    overlap(base.specs.gameModes, other.specs.gameModes) * WEIGHTS.gameMode,
    CAPS.gameMode
  );
  score += Math.min(
    overlap(base.specs.mcVersions, other.specs.mcVersions) * WEIGHTS.mcVersion,
    CAPS.mcVersion
  );

  // Автор — слабый, но настоящий сигнал: у одного строителя узнаваемый
  // почерк, и «ещё от него же» — осмысленное продолжение. Вес маленький
  // намеренно: иначе под каждой картой висели бы просто соседние работы
  // того же автора, и подборка перестала бы зависеть от самой карты.
  if (base.creatorId && other.creatorId && base.creatorId === other.creatorId) {
    score += WEIGHTS.sameCreator;
  }

  return score;
}

/**
 * Похожие карты для страницы товара.
 *
 * @param base карта, под которой показываем подборку
 * @param pool весь каталог витрины (сама карта в нём может быть — уберём)
 * @param limit сколько показать
 *
 * Возвращает ПУСТОЙ массив, если ничего не набрало порога. Это не сбой, а
 * ответ: похожих нет.
 */
export function pickSimilar(
  base: Product,
  pool: Product[],
  limit = 4
): Product[] {
  return pool
    .filter((p) => p.id !== base.id)
    .map((p) => ({ product: p, score: similarityScore(base, p) }))
    .filter((x) => x.score >= MIN_SCORE)
    .sort((a, b) => {
      // Сначала схожесть.
      if (b.score !== a.score) return b.score - a.score;
      // При равной схожести — что ближе по цене: сравнимая цена делает
      // подборку полезнее, чем «то же самое, но втрое дороже».
      const da = Math.abs(a.product.priceCents - base.priceCents);
      const db = Math.abs(b.product.priceCents - base.priceCents);
      if (da !== db) return da - db;
      // Последним — id. Не ради красоты: страница СТАТИЧЕСКАЯ, и при
      // полностью равных картах порядок обязан быть одинаковым от сборки
      // к сборке, иначе подборка молча меняется на каждом деплое.
      return a.product.id.localeCompare(b.product.id);
    })
    .slice(0, limit)
    .map((x) => x.product);
}
