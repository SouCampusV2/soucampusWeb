// JSON для вставки внутрь <script type="application/ld+json">.
//
// ⚠️ JSON.stringify НЕ БЕЗОПАСЕН ВНУТРИ <script>. Он экранирует кавычки и
// обратные слэши — то, что опасно для JSON, — но не `<`. А HTML-парсер
// браузера ищет конец тега раньше, чем кто-либо начнёт читать JSON: строка
// `</script><script>…` в любом значении закрывает наш тег и открывает свой.
//
// Сегодня JsonLd зовут только главная и /about, и данные там — наши
// константы. Но SEO-план требует JSON-LD на странице КАРТЫ, и тогда внутрь
// потечёт название от автора. Ловушка была записана в ARCHITECTURE.md § 7
// ещё в августе с пометкой «лечится одной строкой при добавлении»;
// закрыта заранее 2026-09-22 — строка, которую надо не забыть в будущем,
// хуже строки, которая уже стоит.
//
// `<` → `<` меняет только запись, а не смысл: для JSON-парсера это
// тот же символ, поисковик прочитает ровно то же, что и раньше.
export function toJsonLdScript(data: Record<string, unknown>): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}
