import { describe, it, expect } from "vitest";
import { formatDate, formatDayMonth, formatDayMonthYear } from "./dates";

// Чистые функции форматирования. В сеть не ходят, гоняются в CI без
// ключей (тот же подход, что в creators.test.ts).
//
// Почему это стоит теста: обе ошибки, от которых заведён модуль, тихие.
// Убери локаль — текст поменяется только там, где машина настроена
// иначе, и на своей это незаметно. Убери часовой пояс — дата уедет на
// сутки только западнее (или восточнее) Гринвича.
//
// Отсюда и проверки: точные строки ловят подмену локали на любой
// машине, а метки у края суток ловят пропавший timeZone на всякой
// машине не в UTC — в том числе на рабочей (Киев, UTC+3), где без
// пояса 23:30 UTC отрисовалось бы уже следующим днём.

describe("formatDate", () => {
  it("даёт британский порядок: день, месяц, год", () => {
    expect(formatDate("2026-08-14")).toBe("14/08/2026");
  });

  it("не сдвигает дату у метки перед полуночью UTC", () => {
    expect(formatDate("2026-08-14T23:30:00Z")).toBe("14/08/2026");
  });

  it("не сдвигает дату у метки сразу после полуночи UTC", () => {
    expect(formatDate("2026-08-14T00:30:00Z")).toBe("14/08/2026");
  });

  it("принимает и готовый Date, не только строку", () => {
    expect(formatDate(new Date("2026-08-14T12:00:00Z"))).toBe("14/08/2026");
  });
});

describe("formatDayMonth", () => {
  it("день и месяц словом, без года", () => {
    expect(formatDayMonth("2026-08-14")).toBe("14 Aug");
  });

  it("не сдвигает дату у края суток", () => {
    expect(formatDayMonth("2026-08-14T23:30:00Z")).toBe("14 Aug");
  });
});

describe("formatDayMonthYear", () => {
  it("день, месяц словом и год", () => {
    expect(formatDayMonthYear("2026-08-14")).toBe("14 Aug 2026");
  });

  it("не сдвигает дату у края суток", () => {
    expect(formatDayMonthYear("2026-08-14T23:30:00Z")).toBe("14 Aug 2026");
  });
});
