import sanitizeHtml from "sanitize-html";

// Очистка описания карты — ОДНА функция на все места, где креаторский
// HTML попадает в dangerouslySetInnerHTML.
//
// Зачем вообще: описание пишет посторонний человек в редакторе (Tiptap,
// см. UploadMapForm), а хранится оно как готовый HTML. Вставить такое в
// страницу напрямую — значит позволить автору выполнить свой скрипт в
// браузере каждого посетителя. Поэтому перед показом всё, чего нет в
// белом списке ниже, вырезается.
//
// Почему sanitize-html, а не DOMPurify (было до 2026-08-08):
// DOMPurify не разбирает HTML сам — он просит об этом браузер, а на
// сервере браузера нет, и его подделывает jsdom. На Vercel эта цепочка
// разваливается: внутри jsdom пакет html-encoding-sniffer зовёт через
// require() зависимость, ставшую ESM-модулем, и загрузка падает с
// ERR_REQUIRE_ESM. Ломалось это не одинаково, и потому долго не
// замечалось: /shop/[slug] собирается заранее, на билд-машине, где
// jsdom грузится нормально, а /admin/moderation рендерится в лямбде на
// каждый запрос — и отдавал 500. Тихая часть той же поломки:
// перегенерация страниц товара (ISR, раз в 60с) шла уже в лямбде и
// молча падала, то есть правки описаний не появлялись на проде без
// передеплоя.
//
// sanitize-html разбирает разметку сам, обычным парсером (htmlparser2),
// без DOM и без имитации браузера. Правила те же — меняется только
// инструмент, который их применяет.
//
// БЕЛЫЙ СПИСОК, А НЕ ЧЁРНЫЙ. Перечислено разрешённое, всё остальное
// отбрасывается. Обратный подход («запретить script и onclick»)
// проигрывает по умолчанию: любой не предусмотренный автором список
// вектор проходит насквозь.

// Ровно то, что умеет вставить наш редактор, и ничего сверх. Держать
// синхронно с панелью инструментов UploadMapForm и с оформлением
// RICH_TEXT_CLASS (rich-text.ts) — это три описания одного множества.
const ALLOWED_TAGS = [
  "p", "br", "strong", "em", "s", "code", "pre", "blockquote",
  "h2", "h3", "ul", "ol", "li", "a", "img",
  "table", "thead", "tbody", "tr", "th", "td",
];

/**
 * Описание карты, безопасное для вставки в разметку.
 *
 * Используется И на странице товара, И в админке модерации — намеренно
 * одной функцией: модератор принимает решение, глядя на описание, и
 * обязан видеть ровно то, что получит покупатель. Две копии списка
 * (так было до 2026-08-08) дают самый неприятный вид расхождения —
 * одобрено одно, показано другое.
 */
export function sanitizeDescription(html: string): string {
  return sanitizeHtml(html, {
    allowedTags: ALLOWED_TAGS,

    // Атрибуты разрешаются ПОТЕГОВО, а не общим списком: href уместен у
    // ссылки и не нужен больше нигде. Обработчики событий (onclick,
    // onerror и прочие) сюда не попадают в принципе — их нет в списке.
    allowedAttributes: {
      a: ["href", "target", "rel"],
      img: ["src", "alt"],
      th: ["colspan", "rowspan"],
      td: ["colspan", "rowspan"],
    },

    // Протоколы ссылок. Без этого ограничения href="javascript:…"
    // остался бы обычным атрибутом обычной ссылки и выполнил бы код по
    // клику — тег-то разрешён.
    allowedSchemes: ["http", "https", "mailto"],
    // Картинкам дополнительно data: — редактор показывает только что
    // выбранный файл как data-URI, пока идёт загрузка в Storage.
    allowedSchemesByTag: { img: ["http", "https", "data"] },

    // Чужая ссылка в новой вкладке без noopener даёт открытой странице
    // доступ к window.opener нашей. Дописываем сами, на автора не
    // полагаемся.
    transformTags: {
      a: sanitizeHtml.simpleTransform("a", { rel: "noopener noreferrer" }),
    },
  });
}
