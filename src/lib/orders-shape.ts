// ⚠️ ОТДЕЛЬНЫЙ ФАЙЛ ПО ФИЗИЧЕСКОЙ ПРИЧИНЕ, как comment-shape.ts и
// notification-shape.ts. lib/orders.ts первыми строками тянет
// supabase-admin (служебный ключ) и lib/stripe (серверный SDK) — ему это
// положено, он проводит платежи. Но любой импорт ЗНАЧЕНИЯ оттуда из
// клиентского кода утаскивает оба модуля в браузерный бандл.
//
// ⚠️ И это не гипотеза: найдено замером 2026-09-22. FreshBadge.tsx
// ("use client") брал оттуда FRESH_PURCHASE_MS, upload-client.ts —
// PRODUCT_FILES_BUCKET, и в браузер уезжал чанк на 27 КБ с серверным
// SDK Stripe целиком. На витрине он не использовался НИ РАЗУ — 27 КБ из
// 27 числились у Lighthouse как неиспользуемый JavaScript.
//
// ⚠️ Ключи при этом НЕ утекли — проверено поиском значений
// SUPABASE_SERVICE_ROLE_KEY, STRIPE_SECRET_KEY и VIEW_HASH_SALT по всем
// файлам .next/static: ноль совпадений. У переменных нет префикса
// NEXT_PUBLIC_, и Next их в клиентскую сборку не подставляет. То есть
// цена ошибки была в весе, а не в секретах, — но граница «серверное /
// клиентское» держится не тем, что ключ не подставился, а тем, что
// серверный модуль в браузер не импортируют. Сборка на это не жалуется
// и не пожалуется: молчание здесь ничего не доказывает.
//
// Поэтому здесь лежит только то, что не знает ни про какие ключи: имя
// бакета, срок свежести покупки и чистая функция над датой. Импортов у
// файла нет вовсе, и заводить их не надо — в этом весь смысл.

// Приватный бакет Supabase Storage с файлами карт. Приватный — значит
// прямой ссылки на файл не существует в принципе: скачать можно только
// по временной подписанной ссылке, которую выдаёт signedDownloadUrl в
// orders.ts (там она и осталась — ей нужен служебный ключ).
export const PRODUCT_FILES_BUCKET = "product-files";

/**
 * Сколько времени покупка считается свежей и носит бейдж «NEW».
 *
 * 2026-08-26: ДВЕ МИНУТЫ.
 *
 * Число здесь, а не в базе, потому что это решение о продукте: оно
 * меняется от того, как выглядит список, а не от того, как устроены
 * данные (то же правило, что у лимитов в rate-limit.ts).
 *
 * ⚠️ Две минуты — это по сути «только что вернулся с оплаты». Бейдж
 * дублирует переход со страницы успеха, и это осознанно: он отвечает на
 * вопрос «за чем я сюда пришёл», а не «что у меня новенького».
 */
export const FRESH_PURCHASE_MS = 2 * 60 * 1000;

/**
 * Свежая ли покупка на указанный момент.
 *
 * ⚠️ Считается ОДИН РАЗ, на сервере, в момент рендера страницы: она
 * force-dynamic, но не живая. Открыл список и подождал три минуты —
 * «NEW» останется до перезагрузки. Лечится клиентским таймером, и
 * решено не лечить: через три минуты человек уже нашёл, за чем пришёл.
 *
 * `now` параметром, а не Date.now() внутри, — чтобы функцию можно было
 * спросить о любом моменте, в том числе в тесте.
 */
export function isFreshPurchase(purchasedAt: string, now: number): boolean {
  const at = Date.parse(purchasedAt);
  // Непарсящаяся дата — не повод показывать бейдж: NaN в сравнении даёт
  // false сам по себе, но полагаться на это молча не стоит.
  if (Number.isNaN(at)) return false;
  // Будущее (часы сервера ушли вперёд) считаем свежим: это «только что»
  // с точки зрения человека, а не повод спрятать бейдж.
  return now - at < FRESH_PURCHASE_MS;
}
