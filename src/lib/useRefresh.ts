"use client";

import { useCallback, useTransition } from "react";
import { useRouter } from "next/navigation";

/**
 * Перерисовать серверную часть страницы — так, чтобы это действительно
 * произошло.
 *
 * Казалось бы, для этого есть router.refresh(). Но он доезжает не
 * отовсюду, и это выяснилось дорогой ценой (2026-08-15, см.
 * docs/CHANGELOG.md): один и тот же вызов из обработчика клика работал, а
 * из колбэка WebSocket — нет. Разница в том, идёт ли вызов изнутри
 * события React: там обновление само попадает в нужную очередь, а
 * снаружи — нет.
 *
 * И вот важное следствие, из-за которого этот файл появился. Почти все
 * наши кнопки действия устроены так:
 *
 *     await fetch("/api/...")   // ← здесь обработчик события кончился
 *     router.refresh()          // ← а это уже снаружи
 *
 * После await мы больше НЕ в обработчике, хотя код и написан внутри
 * функции, которую повесили на onClick. То есть «кнопка сработала, а на
 * экране ничего» — не случайность отдельной кнопки, а общее свойство
 * всех, кто обновляет страницу после запроса. Ровно так «Publish again» в
 * каталоге админки молча ничего не делал: карта в базе менялась, экран —
 * нет.
 *
 * startTransition возвращает вызов в правильную очередь независимо от
 * того, откуда он сделан. Один хук на все такие места — чтобы починка не
 * зависела от того, вспомнил ли автор кнопки про эту тонкость.
 */
export function useRefresh(): () => void {
  const router = useRouter();
  const [, startTransition] = useTransition();
  return useCallback(
    () => startTransition(() => router.refresh()),
    [router]
  );
}
