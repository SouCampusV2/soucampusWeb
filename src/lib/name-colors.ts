// ПОЧЕМУ ВЫБОРКА, А НЕ СВОБОДНЫЙ ЦВЕТ (решение владельца 2026-08-20,
// заменило свободный выбор того же дня). Сайт живёт в двух темах, и фон
// под ником в них противоположный: #fbfbff против #09090b. Свободная
// пипетка почти гарантированно даёт цвет, который читается в одной теме
// и пропадает в другой, — причём человек этого не увидит, потому что
// смотрит из своей.
//
// ПОРОГ. Цифры ниже — контраст к обоим фонам, посчитанный по WCAG. Ни
// один насыщенный цвет не берёт 4.5 сразу на светлом и на тёмном: то, что
// хорошо читается на белом, тонет на чёрном. Но ник на профиле — крупный
// жирный текст (text-4xl/5xl), а для него порог WCAG равен 3.0. Все восемь
// с запасом выше; худший — orange, 3.45.
//
// ⚠️ ИЗ ЭТОГО СЛЕДУЕТ ОГРАНИЧЕНИЕ. Палитра рассчитана на КРУПНЫЙ текст.
// Если цвет ника когда-нибудь поедет в мелкие подписи (автор на карточке
// карты, подпись под отзывом), порог там 4.5, и половина списка его не
// возьмёт. Тогда нужна вторая, приглушённая версия каждого цвета — а не
// «и так сойдёт».
//
// ГДЕ ГРАНИЦА ОТВЕТСТВЕННОСТИ. База стережёт ДВА вопроса: кто вправе
// ставить цвет (триггер protect_name_color) и какой формы значение
// (ограничение ^#[0-9a-fA-F]{6}$). Какой именно цвет — вопрос вкуса, а не
// безопасности, поэтому список живёт здесь, в коде: добавить девятый
// оттенок должно быть правкой строки, а не миграцией. Худшее, что даст
// значение вне списка, — некрасивый ник на своей же странице.

export type NameColor = {
  /** Значение, которое уходит в базу и в style. */
  value: string;
  /** Подпись для средства чтения с экрана — кружок сам по себе немой. */
  label: string;
};

export const NAME_COLORS: NameColor[] = [
  { value: "#e11d48", label: "Red" },      // светлая 4.55 · тёмная 4.24
  { value: "#ea580c", label: "Orange" },   // светлая 3.45 · тёмная 5.59
  { value: "#b45309", label: "Amber" },    // светлая 4.86 · тёмная 3.96
  { value: "#15803d", label: "Green" },    // светлая 4.86 · тёмная 3.97
  { value: "#0e7490", label: "Teal" },     // светлая 5.19 · тёмная 3.71
  { value: "#0284c7", label: "Blue" },     // светлая 3.97 · тёмная 4.86
  { value: "#8b5cf6", label: "Violet" },   // светлая 4.10 · тёмная 4.70
  { value: "#db2777", label: "Pink" },     // светлая 4.45 · тёмная 4.33
];

/** Есть ли такой цвет в палитре. */
export function isPaletteColor(value: string | null): boolean {
  return NAME_COLORS.some((c) => c.value === value);
}
