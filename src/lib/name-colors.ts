import type { CSSProperties } from "react";

// Палитра цвета ника — привилегия купивших (миграция 20260820130000).
//
// ПОЧЕМУ ВЫБОРКА, А НЕ СВОБОДНЫЙ ЦВЕТ (решение владельца 2026-08-20,
// заменило свободный выбор того же дня). Сайт живёт в двух темах, и фон
// под ником в них противоположный: #fbfbff против #09090b. Свободная
// пипетка почти гарантированно даёт цвет, который читается в одной теме
// и пропадает в другой, — причём человек этого не увидит, потому что
// смотрит из своей.
//
// ПОРОГ. Цифры ниже — контраст к обоим фонам, посчитанный по WCAG. Ни
// один насыщенный цвет не берёт 4.5 сразу на светлом и на тёмном: то, что
// хорошо читается на белом, тонет на чёрном. Но ник на профиле — крупный
// жирный текст (text-4xl/5xl), а для него порог WCAG равен 3.0. Все восемь
// с запасом выше; худший — orange, 3.45.
//
// МЕЛКИЙ ТЕКСТ (2026-11-14, решение владельца: цветной ник везде). Вне
// профиля ник мелкий — карточки, комментарии, отзывы, навбар, — и порог
// там 4.5, который половина палитры не берёт. Поэтому у каждого цвета есть
// пара оттенков для мелкого текста: `light` для светлой темы, `dark` для
// тёмной, оба не ниже 4.5 на всех фонах сайта (тест в creators.test.ts).
// В базе по-прежнему лежит `value`; пара выбирается при показе через
// nameColorStyle(). Крупный ник на профиле красится самим `value`.

// ГДЕ ГРАНИЦА ОТВЕТСТВЕННОСТИ. База стережёт ДВА вопроса: кто вправе
// ставить цвет (триггер protect_name_color) и какой формы значение
// (ограничение ^#[0-9a-fA-F]{6}$). Какой именно цвет — вопрос вкуса, а не
// безопасности, поэтому список живёт здесь, в коде: добавить девятый
// оттенок должно быть правкой строки, а не миграцией. Худшее, что даст
// значение вне списка, — некрасивый ник на своей же странице.

export type NameColor = {
  /** Значение, которое уходит в базу и в style. */
  value: string;
  /** Подпись для средства чтения с экрана — кружок сам по себе немой. */
  label: string;
  /** Оттенок для мелкого текста на светлой теме (контраст ≥ 4.5). */
  light: string;
  /** Оттенок для мелкого текста на тёмной теме (контраст ≥ 4.5). */
  dark: string;
};

export const NAME_COLORS: NameColor[] = [
  // value — крупный ник: светлая/тёмная. light/dark — мелкий текст.
  { value: "#e11d48", label: "Red", light: "#be123c", dark: "#fb7185" },    // 4.55 · 4.24
  { value: "#ea580c", label: "Orange", light: "#c2410c", dark: "#f97316" }, // 3.45 · 5.59
  { value: "#b45309", label: "Amber", light: "#b45309", dark: "#f59e0b" },  // 4.86 · 3.96
  { value: "#15803d", label: "Green", light: "#15803d", dark: "#22c55e" },  // 4.86 · 3.97
  { value: "#0e7490", label: "Teal", light: "#0e7490", dark: "#06b6d4" },   // 5.19 · 3.71
  { value: "#0284c7", label: "Blue", light: "#0369a1", dark: "#0ea5e9" },   // 3.97 · 4.86
  { value: "#8b5cf6", label: "Violet", light: "#7c3aed", dark: "#a78bfa" }, // 4.10 · 4.70
  { value: "#db2777", label: "Pink", light: "#be185d", dark: "#f472b6" },   // 4.45 · 4.33
];

/** Есть ли такой цвет в палитре. */
export function isPaletteColor(value: string | null): boolean {
  return NAME_COLORS.some((c) => c.value === value);
}

/**
 * style для ника МЕЛКИМ текстом: оттенок под текущую тему.
 *
 * light-dark() выбирает по color-scheme, а он на сайте равен теме
 * (globals.css: html — light, html.dark — dark), поэтому без отдельного
 * CSS. Цвет вне палитры (значение, поставленное до палитры) идёт как
 * есть — это та же форма, которую стережёт база.
 */
export function nameColorStyle(
  value: string | null | undefined
): CSSProperties | undefined {
  if (!value) return undefined;
  const colour = NAME_COLORS.find((c) => c.value === value);
  if (!colour) return { color: value };
  return { color: `light-dark(${colour.light}, ${colour.dark})` };
}
