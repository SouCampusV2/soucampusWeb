// Даты — в одном месте, с явной локалью и явным часовым поясом.
//
// Почему модуль, а не `toLocaleDateString()` по месту. Метод без
// аргументов спрашивает локаль и пояс у того, КТО его выполняет. На
// Vercel это en-US и UTC, у человека в браузере — что стоит у него.
// Значит одна и та же строка кода даёт разный текст на сервере и на
// клиенте, и ломается это двумя разными способами:
//
// 1. Локаль. Пока компонент серверный, текст считается один раз и всё
//    сходится. Стоит перевести его в клиентский — React сверит первый
//    клиентский рендер с серверным HTML посимвольно, увидит «8/14/2026»
//    против «14/08/2026» и уронит гидратацию (#418), перерисовав
//    поддерево и сбросив состояние. Так уже было на уведомлениях, и
//    искали полдня — разбор в шапке NotificationList.tsx.
//
// 2. Часовой пояс, и это хуже. `new Date("2026-08-14")` по спецификации
//    разбирается как полночь UTC. Без `timeZone` она печатается в поясе
//    исполнителя, и западнее Гринвича полночь 14-го — это ещё 13-е.
//    Дата уезжает на сутки, и не в тестах, а у покупателя в отчёте.
//
// Поэтому здесь пришпилено и то и другое. Побочная выгода: формат дат на
// сайте перестаёт зависеть от того, где выполнился код, — раньше он был
// не выбран, а унаследован от настроек Vercel.
//
// Локаль en-GB: она уже выбрана в проекте явно (пауза на заявки в
// /resources, письмо отказа, запасной текст в уведомлениях). Сайт
// англоязычный, день впереди месяца — однозначно читается и не путается
// с американским порядком.

const LOCALE = "en-GB";

/** ISO-время или «2026-08-14» → «14/08/2026». */
export function formatDate(value: string | Date): string {
  return new Date(value).toLocaleDateString(LOCALE, { timeZone: "UTC" });
}

/** «2026-08-14» → «14 Aug». Без года: он есть в подписи периода. */
export function formatDayMonth(value: string | Date): string {
  return new Date(value).toLocaleDateString(LOCALE, {
    day: "numeric",
    month: "short",
    timeZone: "UTC",
  });
}

/** «2026-08-14» → «14 Aug 2026». */
export function formatDayMonthYear(value: string | Date): string {
  return new Date(value).toLocaleDateString(LOCALE, {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  });
}
