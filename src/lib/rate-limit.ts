import { NextResponse } from "next/server";
import { getSupabaseAdmin } from "@/lib/supabase-admin";

// Ограничения частоты на СВОИ обработчики /api/*.
//
// Половина механизма живёт в базе (миграция 20260823120000): там таблица
// ops.rate_events и функция consume_rate_limit, которая одним вызовом
// считает окно и занимает слот. Здесь — вторая половина: сколько чего
// можно и что отвечать, когда нельзя.
//
// ⚠️ Почему числа здесь, а не в базе. Лимит — это решение о продукте
// («сколько раз живой человек делает это в час»), и меняться он будет
// чаще, чем схема. Правка числа не должна требовать миграции. База при
// этом остаётся тем местом, где решение ИСПОЛНЯЕТСЯ: подделать число из
// браузера нельзя, потому что вызов идёт служебным ключом с сервера.
// Тот же раздел обязанностей, что у product-specs.ts.

export type RateLimitRule = {
  /** Сколько раз за окно. */
  limit: number;
  /** Длина окна в секундах. Окно скользящее, не «с начала часа». */
  windowSeconds: number;
  /**
   * Что делать, если сама проверка не сработала (база недоступна).
   *
   * По умолчанию false — «пропустить и громко записать в лог». Довод тот
   * же, что у счётчика просмотров: посетитель пришёл не за нашей
   * защитой, и ронять ему покупку из-за сбоя счётчика — цена выше пользы.
   *
   * true ставится там, где цена ошибки в другую сторону: рассылка на всех
   * пользователей необратима, и лучше не отправить, чем отправить лишнюю.
   */
  failClosed?: boolean;
};

const HOUR = 60 * 60;

// Пятнадцать минут — окно для действий, где отказ достаётся ЖИВОМУ
// человеку, а не скрипту (решение владельца 2026-09-06). Число попыток
// осталось прежним, короче стало ожидание: упёрся в потолок — ждёшь
// четверть часа, а не час.
//
// ⚠️ Меняется ОКНО, а не лимит, и это разные рычаги. Поднять число —
// значит разрешить больше вреда за раз; сузить окно — значит быстрее
// прощать. Ошибившемуся покупателю нужно второе.
const QUARTER_HOUR = 15 * 60;

export const RATE_LIMITS = {
  /**
   * Создание сессии Stripe. Каждый вызов — поход во внешний платный
   * сервис. Живой покупатель нажимает «купить» несколько раз за визит
   * (передумал, вернулся, добавил карту в корзину) — дюжина с запасом.
   * Окно четверть часа: упереться сюда может только настоящий покупатель,
   * и держать его час за то, что он передумал, — наказание не по делу.
   */
  checkout: { limit: 12, windowSeconds: QUARTER_HOUR },

  /**
   * Автор прячет / возвращает / удаляет свою карту. Настоящая работа —
   * единицы действий за сессию; тридцать не заметит никто, кроме скрипта.
   */
  "creator-product": { limit: 30, windowSeconds: HOUR },

  /**
   * Выдача разрешения на загрузку файла карты (шлюз, /api/creator/upload).
   *
   * ⚠️ До 2026-09-11 у загрузок не было лимита ВООБЩЕ: файл летел из
   * браузера прямо в бакет, и нашего кода в этом пути не было. То есть
   * платное хранилище забивалось со скоростью канала, и единственным
   * потолком был размер одного файла.
   *
   * Считается выдача слота, а не загрузка: confirm счёт не тратит,
   * иначе один честный файл списывал бы два. Двадцать в час — это
   * заметно больше, чем бывает настоящей работы (карту заливают раз,
   * переделывают единицы раз), и заметно меньше, чем нужно скрипту.
   */
  "creator-upload": { limit: 20, windowSeconds: HOUR },

  /**
   * Уборка Storage. Самый тяжёлый обработчик из всех: он перечисляет
   * содержимое папок в бакетах и сверяет его с базой.
   *
   * ⚠️ Кнопки у неё нет — её дёргает EditMapForm сам, после КАЖДОГО
   * сохранения правки, и ответа не ждёт. Поэтому потолок считается от
   * числа правок за час, а не от числа нажатий; и поэтому упереться в
   * него безвредно: пропущенная уборка просто подберёт мусор в
   * следующий раз.
   */
  "creator-cleanup": { limit: 20, windowSeconds: HOUR },

  /**
   * Любое действие админки, кроме рассылки: модерация, каталог, заявки,
   * удаление комментариев.
   *
   * ⚠️ Здесь лимит защищает НЕ от постороннего — до этой строки
   * посторонний не доходит, его разворачивает getAdminUser. Он защищает
   * от УГНАННОЙ сессии владельца: с ней за минуту сносится весь каталог.
   * Шестьдесят в час означает, что у беды есть потолок и есть час, чтобы
   * её заметить.
   *
   * Число — компромисс, и это надо знать: разбирая большую очередь
   * модерации подряд, владелец однажды в него упрётся. Тогда его и
   * поднимаем, здесь, одной цифрой.
   */
  "admin-action": { limit: 60, windowSeconds: HOUR },

  /**
   * Ручная рассылка уведомления ВСЕМ пользователям. Единственное действие
   * на сайте, которое одним нажатием достаёт до каждого и не отменяется.
   * Пять в час — это уже много.
   */
  "admin-announce": { limit: 5, windowSeconds: QUARTER_HOUR, failClosed: true },
} as const satisfies Record<string, RateLimitRule>;

export type RateLimitBucket = keyof typeof RATE_LIMITS;

/**
 * Занять слот. Возвращает готовый ответ 429, если нельзя, и null, если
 * можно — чтобы в обработчике это была одна строка:
 *
 *     const limited = await enforceRateLimit("checkout", user.id);
 *     if (limited) return limited;
 *
 * Вызывать ПОСЛЕ проверки прав и ДО самой работы. После прав — чтобы
 * посторонний не расходовал чужой счёт и не выяснял по разнице ответов
 * (404 против 429), что обработчик существует. До работы — потому что
 * смысл в том, чтобы работа не началась.
 */
export async function enforceRateLimit(
  bucket: RateLimitBucket,
  actor: string
): Promise<NextResponse | null> {
  const rule: RateLimitRule = RATE_LIMITS[bucket];

  let retryAfter: number;
  try {
    const { data, error } = await getSupabaseAdmin().rpc("consume_rate_limit", {
      p_bucket: bucket,
      p_actor: actor,
      p_limit: rule.limit,
      p_window_seconds: rule.windowSeconds,
    });
    if (error) throw new Error(error.message);
    retryAfter = typeof data === "number" ? data : 0;
  } catch (err) {
    const why = err instanceof Error ? err.message : String(err);
    // Наружу тихо, внутрь громко — то же правило, что в /api/view.
    // Молчаливо сломавшийся лимит выглядит ровно как работающий, и
    // узнать о нём иначе неоткуда.
    console.error(`[rate-limit] проверка "${bucket}" не сработала: ${why}`);
    if (!rule.failClosed) return null;
    return NextResponse.json(
      { error: "rate limit unavailable" },
      { status: 503 }
    );
  }

  if (retryAfter <= 0) return null;

  return NextResponse.json(
    {
      error: "rate limited",
      // Текст показывается человеку формой. Минуты, а не секунды: «через
      // 43 минуты» понятнее, чем «через 2580 секунд», и точность до
      // секунды здесь никому не нужна.
      message: `Too many requests. Try again in ${Math.ceil(retryAfter / 60)} min.`,
      retryAfter,
    },
    { status: 429, headers: { "Retry-After": String(retryAfter) } }
  );
}
