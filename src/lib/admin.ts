import { createSupabaseServer } from "@/lib/supabase-server";
import { getSupabaseAdmin } from "@/lib/supabase-admin";

// Кто имеет право разбирать очередь модерации.
//
// Проверка ТОЛЬКО серверная и всегда прямо перед действием — у админки
// нет ни одного клиентского гейта, на который можно было бы положиться
// (тот же принцип, что у CreatorOwnerActions: показ кнопки — это UX,
// а не защита).
//
// Читаем флаг служебным ключом, а не сессией пользователя: колонка
// is_admin живёт в profiles, у которой RLS «только своя строка». Свою
// строку пользователь прочитать может, так что технически хватило бы и
// сессии — но тогда право админа зависело бы от политики RLS, которую
// однажды поменяют по другому поводу. Служебный ключ делает источник
// правды однозначным.
//
// ЗДЕСЬ СОЗНАТЕЛЬНО ОСТАЁТСЯ getUser(), а не getCurrentUser() (2026-08-09).
// Страницы кабинета переведены на getClaims() ради скорости: он проверяет
// подпись токена локально, без похода в Supabase (см. lib/current-user.ts).
// Гарантия подлинности там та же, но есть разница, которая для админки
// существенна: локальная проверка подтверждает, что токен НАШ и не истёк,
// и ничего не знает про отзыв. Разлогинился, увели ноутбук, отобрали
// доступ — выданный токен всё равно останется годным до конца своего
// срока. Для «моих покупок» это приемлемо, для права публиковать чужие
// карты — нет. getUser() спрашивает сервер и видит отзыв сразу; лишний
// сетевой поход на одной служебной странице владельца того стоит.

export type AdminUser = {
  id: string;
  email: string | null;
  /**
   * Включён ли у аккаунта двухшаговый вход (привязано приложение-
   * аутентификатор). false — админка работает по одному паролю, и layout
   * показывает об этом плашку.
   */
  twoStep: boolean;
};

/**
 * Чем кончилась проверка права на админку.
 *
 *   ok          — админ, и вход подтверждён так, как требует его аккаунт;
 *   needs-code  — админ с включённым двухшаговым входом, но в ЭТОЙ сессии
 *                 код из приложения ещё не вводили;
 *   denied      — не вошёл или не админ (наружу — 404, без различий).
 */
export type AdminGate =
  | { status: "ok"; admin: AdminUser }
  | { status: "needs-code" }
  | { status: "denied" };

/**
 * Текущий пользователь, если он админ. null — не залогинен, не админ ИЛИ
 * не ввёл код двухшагового входа.
 *
 * Намеренно не различает эти случаи для вызывающего кода: обработчики
 * /api/admin/* на все отвечают 404, чтобы существование админки нельзя
 * было нащупать по разнице ответов. Различать их нужно одному месту —
 * layout админки, который уводит на ввод кода; он зовёт getAdminGate.
 */
export async function getAdminUser(): Promise<AdminUser | null> {
  const gate = await getAdminGate();
  return gate.status === "ok" ? gate.admin : null;
}

/**
 * Проверка права на админку — ЕДИНСТВЕННОЕ место, где она решается.
 *
 * ⚠️ ВТОРОЙ ФАКТОР (аудит 2026-11, S-25). До 12.11 админку открывали
 * пароль или угнанная cookie сессии — и этого хватало, чтобы одобрять
 * карты, слать рассылку всем пользователям и читать почты покупателей.
 *
 * Правило теперь зависит от самого аккаунта:
 *   - приложение-аутентификатор НЕ привязано — как раньше, по сессии.
 *     Не «дыра по умолчанию», а способ не запереть владельца снаружи:
 *     требовать код от того, кому негде его взять, значит закрыть
 *     админку насовсем. Layout в этом случае показывает плашку;
 *   - привязано — сессия обязана быть уровня aal2, то есть код из
 *     приложения введён В НЕЙ. Украденный пароль даёт только aal1.
 *
 * Отвязать приложение, имея одну лишь сессию aal1, нельзя: Supabase сам
 * требует aal2 и для отвязки, и для привязки второго приложения. Так что
 * «сбросить» защиту украденным паролем не выйдет.
 *
 * Уровень берём из токена (getClaims — подпись проверяется локально), а
 * список приложений — из ответа getUser(), который сервер Supabase
 * отдаёт свежим: отвязали приложение — правило изменилось сразу.
 */
export async function getAdminGate(): Promise<AdminGate> {
  // Наружу все отказы выглядят одинаково (404), и это правильно. Но в
  // ЛОГ СЕРВЕРА причину пишем разборчиво: без этого «не пускает» —
  // неотличимо от «сломалось», и чинить приходится вслепую.
  const deny = (why: string): AdminGate => {
    console.warn(`[admin] доступ не выдан: ${why}`);
    return { status: "denied" };
  };

  const supabase = await createSupabaseServer();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return deny("в этом браузере нет сессии — сначала войти на /login");

  let data: { is_admin: boolean } | null = null;
  try {
    const result = await getSupabaseAdmin()
      .from("profiles")
      .select("is_admin")
      .eq("id", user.id)
      .maybeSingle();

    if (result.error) {
      // Колонки нет — значит миграция модерации не прогнана в ЭТОЙ базе.
      // Частый случай: код смотрит в preview, а миграцию прогнали на прод.
      const hint = result.error.message.includes("is_admin")
        ? " — похоже, миграция 20260730140000_moderation не прогнана в базе, на которую смотрит .env.local"
        : "";
      return deny(`запрос profiles.is_admin не удался: ${result.error.message}${hint}`);
    }
    data = result.data as { is_admin: boolean } | null;
  } catch (err) {
    // getSupabaseAdmin бросает, если нет SUPABASE_SERVICE_ROLE_KEY.
    return deny(err instanceof Error ? err.message : "служебный клиент недоступен");
  }

  // В лог — id, а не почта (аудит 2026-11, S-27). Сюда попадает КАЖДЫЙ
  // вошедший, кто открыл /admin, а логи Vercel читает не только владелец
  // базы; почта в них — персональные данные без надобности. По id строка
  // находится так же.
  if (!data) return deny(`у пользователя ${user.id} нет строки в profiles`);
  if (!data.is_admin) {
    return deny(
      `у пользователя ${user.id} is_admin = false. ` +
        `Проверить: select username, is_admin from profiles where id = '${user.id}';`
    );
  }

  // Привязано ли приложение. Считается только подтверждённое (verified):
  // начатая и брошенная привязка кодов не выдаёт, и требовать по ней код
  // значило бы запереть человека.
  const twoStep = (user.factors ?? []).some((factor) => factor.status === "verified");

  if (twoStep) {
    const { data: claimsData } = await supabase.auth.getClaims();
    const level = (claimsData?.claims as { aal?: string } | undefined)?.aal;
    if (level !== "aal2") {
      console.warn(`[admin] нужен код двухшагового входа: у ${user.id} сессия уровня ${level ?? "?"}`);
      return { status: "needs-code" };
    }
  }

  return { status: "ok", admin: { id: user.id, email: user.email ?? null, twoStep } };
}
