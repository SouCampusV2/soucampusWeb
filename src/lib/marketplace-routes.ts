// Какие адреса считаются «страницами магазина».
//
// Список был вшит в Navbar: там он решал, показывать пилюлю портфолио или
// магазинную. Потом тот же вопрос понадобился PricingSection («не
// показывать тарифы в магазине»), и второй такой же список неизбежно
// разъехался бы с первым — ровно так уже разъезжались семь копий
// градиента и семь форматов даты. Поэтому список один и живёт здесь.
//
// Что сюда входит и почему. Не только сам маркетплейс: вход, регистрация,
// сброс пароля и личный кабинет — часть флоу покупки (покупка требует
// аккаунта), и переключение оформления посреди «войти → забыл → задать
// новый» выглядело бы так, будто человека выкинуло на другой сайт.
// Профиль продавца — тоже магазин, это его витрина.

const EXACT = new Set([
  "/marketplace",
  "/cart",
  // Вики — магазинная страница, а не студийная (замечание владельца
  // 2026-09-06). Её ссылка живёт в SHOP_NAV_LINKS и в футерной колонке
  // Marketplace, то есть попасть в неё можно только из магазина, — а
  // навбар там до сих пор рисовался портфолийный. Забыли внести сюда,
  // когда вики появилась 02.09.
  "/wiki",
  "/support",
  "/login",
  "/signup",
  "/forgot-password",
  "/reset-password",
  "/link-expired",
  "/settings",
  "/purchases",
  "/notifications",
]);

// "/@" и "/u/" — профиль. Оба, потому что адрес у него один снаружи и
// другой внутри: /@soucampus это rewrite на /u/soucampus (next.config.ts).
// usePathname() отдаёт то, что видит человек, то есть «/@…», — но зайти
// напрямую по /u/… тоже можно, и навбар там обязан выглядеть так же.
// "/creator" здесь БОЛЬШЕ НЕТ (2026-08-28). Он держался ради
// /creator/upload — единственного, что оставалось под этим адресом
// после переезда профиля 21.08. Форма ушла в админку, у админки свой
// layout без навбара, и спрашивать про неё нечего: под /creator не
// осталось ни одной страницы, только редиректы в next.config.ts.
//
// ⚠️ Этот же комментарий 21.08 предупреждал, что upload там ещё живёт —
// и в тот же день редирект /creator/:username её похоронил. Знание
// лежало в одном файле, правка делалась в другом.
const PREFIXES = [
  "/marketplace/",
  // Статьи вики — по той же причине, что и корень выше.
  "/wiki/",
  "/profile",
  "/resources",
  "/@",
  "/u/",
];

export function isMarketplaceRoute(pathname: string): boolean {
  if (EXACT.has(pathname)) return true;
  return PREFIXES.some((prefix) => pathname.startsWith(prefix));
}
