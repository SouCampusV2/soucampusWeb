"use client";

import { useEffect, useId, useRef } from "react";
import { createSupabaseBrowser } from "@/lib/supabase-browser";

/**
 * Подписка на СВОИ уведомления по WebSocket.
 *
 * Зачем вообще: до этого про новое уведомление узнавали, только если
 * человек что-то сделал — открыл страницу, перешёл по ссылке, нажал
 * «обновить». Пока он просто смотрел в открытую вкладку, площадка
 * молчала. Уведомление по определению приходит без спроса, поэтому
 * опрашивать сервер здесь неправильно: событие есть у базы, и она умеет
 * о нём сказать сама (Supabase Realtime / Postgres Changes).
 *
 * Почему не «раз в N секунд спрашивать»: опрос стоит запроса с каждой
 * открытой вкладки каждые N секунд независимо от того, случилось ли
 * что-нибудь, и всё равно опаздывает на эти N секунд. Подписка — одно
 * соединение, которое молчит, пока молчать нечего.
 *
 * Безопасность отдельного кода не потребовала: Postgres Changes проверяет
 * ту же RLS, что и обычный запрос (политика "read own notifications"),
 * для каждого подписчика отдельно. Чужую строку сюда не пришлют по той же
 * причине, по которой её нельзя прочитать. Фильтр по user_id ниже — это
 * не защита, а экономия: не гонять по сети то, что RLS всё равно отрежет.
 */
export function useNotificationEvents(
  userId: string | null,
  /** Пришло новое уведомление. */
  onInsert?: () => void,
  /** Существующее изменилось — почти всегда «прочитано» в другой вкладке. */
  onUpdate?: () => void
) {
  // Обработчики в ref, а не в зависимостях эффекта: подписка стоит
  // рукопожатия по сети, и пересоздавать её из-за того, что родитель
  // перерисовался и передал новую стрелочную функцию, — верный способ
  // получить отписку-подписку на каждый рендер.
  const insertRef = useRef(onInsert);
  const updateRef = useRef(onUpdate);

  // Свой идентификатор на каждый вызов хука — из него собирается имя
  // канала (зачем именно так, подробно у самого канала ниже).
  const channelId = useId();

  // Обновляем ref в эффекте, а не прямо в теле хука: запись в ref во
  // время рендера — то самое, за что ругается react-hooks/refs (рендер
  // обязан быть чистым, а React вправе его выбросить и повторить).
  // Эффект без зависимостей отрабатывает после каждого рендера и стоит
  // ВЫШЕ подписки: порядок эффектов — порядок объявления, значит к
  // моменту первого подключения к каналу в ref уже лежат обработчики.
  useEffect(() => {
    insertRef.current = onInsert;
    updateRef.current = onUpdate;
  });

  useEffect(() => {
    if (!userId) return;

    const supabase = createSupabaseBrowser();
    // Токен сессии на самом сокете: без него канал подключится, но RLS
    // увидит анонима, и своих же строк подписчик не получит.
    void supabase.realtime.setAuth();

    // Имя канала уникально для КАЖДОГО вызова хука, а не одно на
    // пользователя. Это не украшение — на этом уронился прод.
    //
    // Колокол в навбаре отрисован ДВАЖДЫ (десктопный и мобильный, второй
    // спрятан css, но в DOM он есть), то есть хук вызывается дважды с
    // одним userId. А supabase.channel(topic) на уже существующей теме
    // НЕ создаёт второй канал — он возвращает первый (см.
    // RealtimeClient.channel). Значит второй колокол дописывал свои
    // подписки в чужой, уже подключающийся канал.
    //
    // Дальше ломается тонко: клиент отправляет серверу список своих
    // postgres_changes при подключении, а ответ сверяет с ним ПО
    // ПОРЯДКУ (_updatePostgresBindings). К моменту ответа подписок стало
    // четыре вместо двух, для лишних сверять нечего — клиент считает это
    // рассогласованием, отписывается и подключается заново. И так по
    // кругу: постоянный join → ошибка → повторный join, вкладка ест
    // процессор и память, пока Chrome её не убьёт. Ровно это и было
    // видно: страница успевает отрисоваться и падает.
    //
    // Уникальная тема даёт каждому вызову свой канал и свои подписки, и
    // хук становится безопасным при любом числе вызовов — не только при
    // сегодняшних двух.
    const channel = supabase
      .channel(`notifications:${userId}:${channelId}`)
      .on(
        "postgres_changes",
        {
          event: "INSERT",
          schema: "public",
          table: "notifications",
          filter: `user_id=eq.${userId}`,
        },
        () => insertRef.current?.()
      )
      .on(
        "postgres_changes",
        {
          event: "UPDATE",
          schema: "public",
          table: "notifications",
          filter: `user_id=eq.${userId}`,
        },
        () => updateRef.current?.()
      );

    // subscribe() вызывается отдельно, а не в той же цепочке: колбэк
    // ниже обращается к channel, и в одном выражении он ссылался бы на
    // переменную, которой ещё не существует.
    channel.subscribe((status) => {
      // Предохранитель. Realtime сам переподключается при ошибке, и это
      // правильно для обрыва связи — но неправильно для ошибки, которая
      // повторится при каждой попытке (таблицы нет в публикации, права
      // не те, рассогласование подписок). Такая пара «ошибка →
      // переподключение» крутится бесконечно и убивает вкладку.
      //
      // Уведомления — не то, ради чего можно положить магазин. Поэтому
      // при ошибке канала мы уходим совсем: колокол возвращается к тому
      // поведению, что было раньше (пересчёт при открытии страницы и при
      // переходе), кнопка «обновить» на странице никуда не делась. Хуже,
      // чем задумано, но не хуже, чем было до всей этой работы.
      if (status === "CHANNEL_ERROR" || status === "TIMED_OUT") {
        console.warn(
          `Уведомления в реальном времени недоступны (${status}) — остаёмся на ручном обновлении.`
        );
        void supabase.removeChannel(channel);
      }
    });

    // Канал закрываем, а не просто отписываемся: иначе при переходах
    // между страницами соединения копятся, а на бесплатном плане их
    // число ограничено.
    return () => {
      void supabase.removeChannel(channel);
    };
  }, [userId, channelId]);
}
