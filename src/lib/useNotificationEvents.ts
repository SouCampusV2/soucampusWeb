"use client";

import { useEffect, useRef } from "react";
import type { RealtimeChannel } from "@supabase/supabase-js";
import { createSupabaseBrowser } from "@/lib/supabase-browser";

/**
 * Подписка на СВОИ уведомления по WebSocket.
 *
 * Зачем вообще: до этого про новое уведомление узнавали, только если
 * человек что-то сделал — открыл страницу, перешёл по ссылке, нажал
 * «обновить». Пока он просто смотрел в открытую вкладку, площадка
 * молчала. Уведомление по определению приходит без спроса, поэтому
 * опрашивать сервер здесь неправильно: событие есть у базы, и она умеет
 * о нём сказать сама (Supabase Realtime / Postgres Changes).
 *
 * Безопасность отдельного кода не потребовала: Postgres Changes проверяет
 * ту же RLS, что и обычный запрос (политика "read own notifications"),
 * для каждого подписчика отдельно. Чужую строку сюда не пришлют по той же
 * причине, по которой её нельзя прочитать. Фильтр по user_id — это не
 * защита, а экономия: не гонять по сети то, что RLS всё равно отрежет.
 *
 * ------------------------------------------------------------------
 * ОДИН канал на пользователя, сколько бы мест его ни слушало.
 *
 * Это третья и, наконец, правильная попытка — предыдущие две стоят того,
 * чтобы их записать, потому что обе казались разумными.
 *
 * Сначала имя канала собиралось из одного userId. Колокол в навбаре
 * отрисован дважды (десктопный и мобильный), то есть хук вызывался
 * дважды, а supabase.channel(topic) на существующей теме возвращает УЖЕ
 * СОЗДАННЫЙ канал. Второй вызов дописывал свои подписки в чужой,
 * подключающийся канал; клиент сверяет ответ сервера со своим списком по
 * порядку, лишним подпискам сверять было нечего — он считал это
 * рассогласованием и переподключался. Бесконечно. Вкладка умирала.
 *
 * Тогда каждому вызову выдали своё имя. Падать перестало, но на одном
 * сокете оказалось три канала с одинаковыми фильтрами — и события стали
 * доходить не до всех: колокол загорался, а список молчал.
 *
 * Значит дело не в именах. Дублировать подписку на одни и те же строки
 * не нужно вовсе: канал должен быть ОДИН, а слушателей у него сколько
 * угодно. Ниже — ровно это: канал заводится при первом слушателе,
 * закрывается при последнем, а событие раздаётся всем. Заодно это честно
 * по отношению к лимиту одновременных подключений.
 * ------------------------------------------------------------------
 */

type Listener = { onInsert?: () => void; onUpdate?: () => void };

// Живой канал и его слушатели. Модульный уровень, а не React-состояние:
// канал должен переживать размонтирование отдельного компонента, иначе
// уход с одной страницы рвал бы подписку у навбара, который никуда не
// девался.
let shared: {
  userId: string;
  channel: RealtimeChannel;
  listeners: Set<Listener>;
} | null = null;

function emit(kind: "insert" | "update") {
  if (!shared) return;
  // Копия перед обходом: обработчик вправе отписаться прямо в себе.
  for (const listener of Array.from(shared.listeners)) {
    if (kind === "insert") listener.onInsert?.();
    else listener.onUpdate?.();
  }
}

function attach(userId: string, listener: Listener) {
  // Сменился пользователь (вход под другим аккаунтом) — старый канал
  // больше не про него.
  if (shared && shared.userId !== userId) {
    void createSupabaseBrowser().removeChannel(shared.channel);
    shared = null;
  }

  if (shared) {
    shared.listeners.add(listener);
    return;
  }

  const supabase = createSupabaseBrowser();

  const filter = {
    schema: "public",
    table: "notifications",
    filter: `user_id=eq.${userId}`,
  } as const;

  const channel = supabase
    .channel(`notifications:${userId}`)
    .on("postgres_changes", { ...filter, event: "INSERT" }, () => emit("insert"))
    .on("postgres_changes", { ...filter, event: "UPDATE" }, () => emit("update"));

  // Канал регистрируем СРАЗУ, ещё до присоединения: следующий слушатель
  // должен встать к этому каналу, а не завести второй, пока мы ждём
  // токен. Дублирование каналов уже роняло вкладку — см. историю выше.
  shared = { userId, channel, listeners: new Set([listener]) };

  // Токен сессии кладём на сокет и ДОЖИДАЕМСЯ этого, прежде чем
  // присоединяться. Здесь была настоящая причина тишины.
  //
  // Realtime проверяет RLS от имени того, чей токен на сокете. Политика
  // у нас `for select to authenticated` — а без токена подписчик для
  // базы аноним, и ни одной строки ему не положено. Дальше происходит
  // самое неприятное: канал присоединяется УСПЕШНО (для присоединения
  // строки не нужны, статус честный SUBSCRIBED), а событий не приходит
  // никогда и жаловаться не на что. Ровно это мы и наблюдали: живой
  // канал, три слушателя, ноль событий, ноль ошибок.
  //
  // setAuth() асинхронный, а вызывался без ожидания — и запрос на
  // присоединение уходил раньше, чем приезжал токен. В самом
  // supabase-js токен попадает в этот запрос, только если он УЖЕ на
  // сокете (RealtimeChannel.subscribe: `if (this.socket.accessTokenValue)`),
  // так что гонку мы выигрывали стабильно и не в свою пользу.
  void supabase.realtime.setAuth().then(() => {
    // Пока ждали, канал могли закрыть (ушли со страницы, сменился
    // пользователь). Присоединять покойника незачем.
    if (shared?.channel !== channel) return;
    channel.subscribe((status) => {
      // Предохранитель. Realtime сам переподключается при ошибке, и это
      // правильно для обрыва связи — но неправильно для ошибки, которая
      // повторится при каждой попытке (таблицы нет в публикации, права
      // не те). Такая пара «ошибка → переподключение» крутится
      // бесконечно и убивает вкладку — это уже случалось.
      //
      // Уведомления не то, ради чего можно положить магазин: при ошибке
      // канала уходим совсем. Колокол вернётся к пересчёту при открытии
      // страницы, а список — к кнопке «обновить».
      if (status === "CHANNEL_ERROR" || status === "TIMED_OUT") {
        console.warn(
          `Уведомления в реальном времени недоступны (${status}) — остаёмся на ручном обновлении.`
        );
        detachAll();
      }
    });
  });
}

function detachAll() {
  if (!shared) return;
  void createSupabaseBrowser().removeChannel(shared.channel);
  shared = null;
}

function detach(listener: Listener) {
  if (!shared) return;
  shared.listeners.delete(listener);
  // Последний ушёл — гасим свет. Держать открытый сокет ради никого
  // незачем, а при следующем слушателе канал поднимется заново.
  if (shared.listeners.size === 0) detachAll();
}

export function useNotificationEvents(
  userId: string | null,
  /** Пришло новое уведомление. */
  onInsert?: () => void,
  /** Существующее изменилось — почти всегда «прочитано» в другой вкладке. */
  onUpdate?: () => void
) {
  // Обработчики в ref, а не в зависимостях эффекта: подписка стоит
  // рукопожатия по сети, и пересоздавать её из-за того, что родитель
  // перерисовался и передал новую стрелочную функцию, — верный способ
  // получить отписку-подписку на каждый рендер.
  const insertRef = useRef(onInsert);
  const updateRef = useRef(onUpdate);

  // Обновляем ref в эффекте, а не в теле хука: запись в ref во время
  // рендера — то, за что справедливо ругается react-hooks/refs. Эффект
  // без зависимостей отрабатывает после каждого рендера и стоит ВЫШЕ
  // подписки: порядок эффектов — порядок объявления, значит к моменту
  // подключения в ref уже лежат обработчики.
  useEffect(() => {
    insertRef.current = onInsert;
    updateRef.current = onUpdate;
  });

  useEffect(() => {
    if (!userId) return;

    // Запись в общий список — своя на каждый вызов хука, а зовёт она
    // всегда актуальный обработчик через ref.
    const listener: Listener = {
      onInsert: () => insertRef.current?.(),
      onUpdate: () => updateRef.current?.(),
    };

    attach(userId, listener);
    return () => detach(listener);
  }, [userId]);
}
