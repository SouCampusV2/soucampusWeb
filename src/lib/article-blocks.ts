// Язык, на котором написаны тексты сайта: статьи Wiki и посты What's new.
//
// Жил внутри wiki.ts, пока статьи были одни. 2026-09-15 появились посты
// (updates.ts), и у них ровно тот же вопрос — абзац, шаги, список,
// оговорка. Две копии типа означали бы два отрисовщика, а два отрисовщика
// разъезжаются: свечение жило в семи копиях, ссылки «назад» — в пяти, и
// каждый раз это стоило отдельного дня. Поэтому тип один и лежит здесь,
// а рисует его один компонент — ArticleBody.tsx.
//
// Тело — размеченные БЛОКИ, а не строка с HTML. HTML в данных пришлось бы
// выводить через dangerouslySetInnerHTML, то есть завести второй путь для
// разметки на сайте, где для описаний карт уже есть sanitize.ts. Блоки же
// превращает в разметку отрисовщик, и вставить в них тег физически нечем.

/** Кусок текста. Разметки внутри строк нет намеренно — см. выше. */
export type ArticleBlock =
  | { kind: "text"; text: string }
  | { kind: "steps"; items: string[] }
  | { kind: "list"; items: string[] }
  | { kind: "note"; text: string }
  | {
      kind: "image";
      /**
       * Только файл из public/, путь от корня ("/portfolio/…"). Чужой
       * адрес сюда не пускает тест: картинка с постороннего сервера —
       * это IP каждого читателя у постороннего, то самое, что закрыто
       * для описаний карт и аватаров из Google.
       */
      src: string;
      alt: string;
      /**
       * Настоящие размеры файла. Рамка повторяет пропорцию исходника, а
       * не навязывает свою (DESIGN.md → «Вёрстка», урок трёх карточек
       * 28.08): скриншоты бывают и 16:9, и 2.4:1, и обрезать широкий
       * кадр под 16:9 значит отрезать ему бока.
       */
      width: number;
      height: number;
      caption?: string;
    };

/** Раздел текста: заголовок и блоки под ним. */
export type ArticleSection = { heading: string; blocks: ArticleBlock[] };
