"use client";

import { useSyncExternalStore } from "react";

// Возвращает false во время серверного рендера И на ПЕРВОМ клиентском
// рендере (гидратации), затем — сразу true.
//
// Зачем: наши страницы статические (собраны заранее, один HTML на всех).
// Сервер не знает ни корзину (она в localStorage браузера), ни то, кто
// залогинен, — поэтому в готовом HTML этих данных нет. Правило React:
// первый клиентский рендер обязан совпасть с серверным HTML, иначе
// гидратация «расходится». Значит показать настоящее состояние браузера
// можно только ПОСЛЕ гидратации. Этот хук и есть переключатель «уже
// можно»: пока он false — рисуем нейтральную заглушку (а не заведомо
// неверное «Add to cart» / «войти»), как только true — реальное значение.
//
// Реализовано через useSyncExternalStore без подписки: getServerSnapshot
// отдаёт false, getSnapshot — true. React сам использует серверный
// снимок на гидратации и клиентский сразу после неё. Так обходимся без
// setState-в-эффекте (лишний каскадный рендер, которого мы избегаем — см.
// комментарии в cart-context.tsx / ThemeProvider.tsx).
const subscribe = () => () => {};

export function useHydrated(): boolean {
  return useSyncExternalStore(
    subscribe,
    () => true, // клиент, после гидратации
    () => false, // сервер + первый клиентский рендер
  );
}
