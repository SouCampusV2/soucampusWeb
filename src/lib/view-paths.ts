// Какие адреса считаются в статистике просмотров.
//
// Отдельный файл, а не часть views.ts, по одной причине: этот список
// нужен И серверу (/api/view проверяет, что ему прислали), И браузеру
// (ViewTracker не отправляет то, в чём заведомо откажут). А views.ts
// импортирует supabase-admin со служебным ключом — такому модулю в
// клиентском бандле не место, и Next справедливо на это ругается.
//
// Здесь только чистые строки и одна функция без зависимостей, поэтому
// файл безопасно попадает в обе стороны.

// Пути, по которым считаются просмотры. Собраны здесь, чтобы обработчик
// /api/view и страницы, которые показывают счётчик, пользовались одними
// и теми же строками и не разъехались из-за опечатки.
export const VIEW_PATHS = {
  portfolio: "/portfolio",
  project: (slug: string) => `/portfolio/${slug}`,
} as const;

// Статические страницы сайта. Динамические (работы и отзывы) проверяются
// шаблоном ниже — перечислять 16 адресов вручную бессмысленно, они
// меняются вместе с содержимым базы.
//
// Личный кабинет, корзина, вход и админка сюда НЕ входят и не должны:
// счётчик существует ради публичного портфолио и витрины, а сколько раз
// человек открыл собственные настройки — не статистика сайта.
const STATIC_PATHS = new Set([
  "/",
  "/portfolio",
  "/about",
  "/contact",
  "/shop",
  "/terms",
]);

// Разрешённые к подсчёту пути. Обработчик принимает только их: иначе
// кто угодно мог бы засорить таблицу произвольными строками ("/выдумка"),
// и она росла бы бесконтрольно. Шаблон slug'а намеренно узкий — строчные
// латинские буквы, цифры и дефис, ровно то, что порождает БД.
export function isTrackablePath(path: string) {
  if (STATIC_PATHS.has(path)) return true;
  return /^\/(portfolio|reviews|shop)\/[a-z0-9-]{1,80}$/.test(path);
}
