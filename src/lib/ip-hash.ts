import { createHash } from "crypto";

// Отпечаток IP-адреса вместо самого адреса. Общий для счётчика
// просмотров (/api/view) и журнала скачиваний (/api/download) — вынесен
// сюда 2026-09-26, когда потребителей стало два: две копии одной
// формулы разошлись бы, и хэши из двух таблиц перестали бы
// сравниваться между собой.
//
// Сам IP не сохраняем: он считается персональными данными, а для наших
// задач достаточно необратимого отпечатка. Соль нужна, чтобы хэш нельзя
// было подобрать перебором — адресов всего около четырёх миллиардов.
//
// Только адрес, без User-Agent: раньше он входил в хэш счётчика, и
// достаточно было менять строку браузера, чтобы каждый раз получать
// чистый лимит.
export function hashIp(ip: string, secret: string): string {
  return createHash("sha256").update(`${secret}:${ip}`).digest("hex");
}

/** Настоящий адрес за прокси Vercel приходит заголовком. */
export function clientIp(headerList: Headers): string {
  return (
    headerList.get("x-forwarded-for")?.split(",")[0].trim() ||
    headerList.get("x-real-ip") ||
    "unknown"
  );
}
