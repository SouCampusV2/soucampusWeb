import { CartView } from "@/components/CartView";

// Серверная обёртка корзины (2026-09-26). Всё содержимое — клиентский
// CartView; здесь только то, что знает один сервер: какой ключ Stripe
// стоит в этом окружении.
//
// Плашка «демо, карта 4242» показывается, пока ключ не живой. Поставил
// в Vercel sk_live_… — после деплоя плашка пропадает сама; на preview
// остаются тестовые ключи, и плашка там остаётся, как и должна.
//
// ⚠️ Страница статическая: ключ читается на СБОРКЕ. Сменил ключ в
// Vercel — нужен редеплой, как и для любой переменной окружения.
// Нет ключа вовсе — считаем тестом: честнее лишний раз предупредить.
export default function CartPage() {
  const stripeTestMode = !process.env.STRIPE_SECRET_KEY?.startsWith("sk_live_");
  return <CartView stripeTestMode={stripeTestMode} />;
}
