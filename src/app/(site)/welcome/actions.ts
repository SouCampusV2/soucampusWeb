"use server";

import { cookies } from "next/headers";
import {
  NAME_CLAIMED_COOKIE,
  NAME_CLAIMED_COOKIE_OPTIONS,
} from "@/lib/name-claimed-cookie";

/**
 * Признак «этот человек уже назвался» — для гейта в proxy.ts.
 *
 * ⚠️ ЭТО ПОДСКАЗКА, А НЕ ПРАВО, и разница здесь принципиальная.
 *
 * Гейт нужен, чтобы человек, вошедший через Google, попал на /welcome, а
 * не бродил по сайту под именем вида `stavytskyiyevhenii`, придуманным
 * базой из его почты. Чтобы это проверить, надо спросить у базы колонку
 * username_claimed — а proxy срабатывает на КАЖДОМ переходе, и лишний
 * запрос на каждый переход каждого вошедшего дорог.
 *
 * Поэтому: cookie есть — не спрашиваем; cookie нет — спрашиваем один раз
 * и ставим её. Запрос остаётся только в короткое окно до выбора имени.
 *
 * ПОЧЕМУ ПОДДЕЛКА COOKIE ЗДЕСЬ БЕЗОБИДНА. Подделав её, человек пропустит
 * ЭКРАН — и не получит ни одного права: бесплатная смена имени по-прежнему
 * висит на колонке username_claimed, а её из браузера не изменить
 * (guard_username_change возвращает значение из old прежде любых решений,
 * миграция 20260825120000). То есть худшее последствие — человек остался
 * с именем из почты, чего сам и добивался.
 *
 * ⚠️ Если когда-нибудь от этой cookie начнёт зависеть что-то, кроме
 * показа экрана, — её придётся подписывать, как visitor-cookie.ts.
 * Правило то же, что и везде: запрет ставится там, где стоит разрешение,
 * а разрешение здесь живёт в базе.
 *
 * ⚠️ Само имя и настройки лежат в src/lib/name-claimed-cookie.ts, а не
 * здесь: файл с "use server" умеет экспортировать ТОЛЬКО async-функции,
 * а proxy.ts, который эту cookie читает, живёт в Edge и не должен тянуть
 * next/headers.
 */
export async function markNameClaimed() {
  const jar = await cookies();
  jar.set(NAME_CLAIMED_COOKIE, "1", NAME_CLAIMED_COOKIE_OPTIONS);
}
