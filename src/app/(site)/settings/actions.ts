"use server";

import { revalidatePath } from "next/cache";

// Сброс кэша публичного профиля после правки.
//
// ЗАЧЕМ ЭТО ВООБЩЕ СУЩЕСТВУЕТ. Страница /creator/[username] собирается
// заранее (generateStaticParams) и живёт с revalidate = 60, унаследованным
// от группы (site). А форма настроек пишет в profiles ПРЯМО ИЗ БРАУЗЕРА —
// нашего серверного кода в этом пути нет вовсе. Значит, и сбросить кэш
// после записи некому: до минуты человек видит собственный профиль со
// старым ником, старым аватаром и старым цветом и решает, что сохранение
// не сработало. Ровно на этом владелец и споткнулся 2026-08-21 с цветом
// ника.
//
// ПОЧЕМУ НЕ force-dynamic. Это тоже сняло бы задержку — ценой того, что
// каждый публичный профиль перестал бы быть статикой и считался бы на
// каждый заход постороннего. Профили публичны и читаются куда чаще, чем
// правятся; платить за редкую запись постоянным рендером неверно.
//
// ⚠️ Действие ничего не проверяет и не должно: revalidatePath не отдаёт
// данных и не меняет их — он лишь помечает готовый HTML устаревшим.
// Худшее, что даст злоупотребление, — лишняя пересборка чужой страницы,
// которая и так пересобирается раз в минуту.
export async function revalidateProfile(username: string) {
  if (!username) return;
  revalidatePath(`/creator/${username}`);
}
