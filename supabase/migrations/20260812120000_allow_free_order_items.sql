-- ============================================================
-- Ноль — законная цена. 2026-08-12.
--
-- СРОЧНАЯ ПРАВКА: страница успеха отдавала 500 после покупки корзины,
-- в которой была бесплатная карта.
--
-- История в двух шагах. Сначала бесплатная карта молча выпадала из
-- заказа: разбор строк Stripe отбрасывал позиции с ценой <= 0 (см.
-- orders.ts). Это починили 11.08 — и упёрлись в то же самое допущение
-- уровнем ниже, в схеме:
--
--   price_cents integer not null check (price_cents > 0)
--   total_cents integer not null check (total_cents > 0)
--
-- Оба ограничения писались в июле, когда все карты стоили денег, и
-- тогда «цена больше нуля» звучало как «цена вообще есть». С появлением
-- бесплатных карт это перестало быть правдой, но проверки остались.
--
-- Итог был хуже, чем до правки: раньше терялась одна позиция, а теперь
-- падала запись ВСЕГО заказа (record_paid_order пишет заказ и позиции
-- одной транзакцией — она либо вся проходит, либо вся нет). Покупатель
-- платил и не получал ничего.
--
-- Меняем > 0 на >= 0. Отрицательная цена по-прежнему невозможна — вот
-- она действительно бессмысленна, а ноль осмыслен: это цена, которую
-- креатор поставил сознательно, и позиция заказа с ней нужна, иначе
-- покупателю нечего скачивать.
--
-- Нулевой total_cents — тоже законный случай: корзина из одних
-- бесплатных карт.
--
-- Правило миграций: сначала preview, потом прод (docs/RULES.md). Эту
-- гнать НЕМЕДЛЕННО на обоих: без неё смешанная корзина не покупается.
-- ============================================================

alter table public.order_items drop constraint if exists order_items_price_cents_check;
alter table public.order_items
  add constraint order_items_price_cents_check check (price_cents >= 0);

alter table public.orders drop constraint if exists orders_total_cents_check;
alter table public.orders
  add constraint orders_total_cents_check check (total_cents >= 0);

-- quantity трогать НЕ надо: количество ноль означало бы позицию, которой
-- нет, — а это не «бесплатно», а «не покупали».
