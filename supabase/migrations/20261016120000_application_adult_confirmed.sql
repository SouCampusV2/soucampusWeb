-- ------------------------------------------------------------
-- Подтверждение «мне есть 18» в заявке на статус креатора.
--
-- Решение владельца к разморозке креаторства (docs/SCANNER.md § 1):
-- авторы — только 18+. Минимум — галочка в заявке, сохранённая в базе
-- с датой. Дата, а не boolean: «когда человек это подтвердил» — то, что
-- спросят при споре, и true без даты на этот вопрос не отвечает.
--
-- ДОБАВЛЯЮЩАЯ миграция — прогонять ДО деплоя кода, который её пишет
-- (/api/creator/application).
--
-- Колонка допускает NULL намеренно: старые заявки поданы без галочки, и
-- приписать им подтверждение задним числом было бы враньём. Новая
-- заявка без даты не встанет — это держит обработчик, а не ограничение:
-- писать в таблицу больше некому (политики вставки нет с 20.08, и
-- возвращать её не будем — см. src/lib/flags.ts).
-- ------------------------------------------------------------
alter table public.creator_applications
  add column if not exists adult_confirmed_at timestamptz;

notify pgrst, 'reload schema';

-- ------------------------------------------------------------
-- Журнал прогонов — последней строкой (docs/RULES.md → «Миграции»).
-- ------------------------------------------------------------
insert into ops.applied_migrations (version)
values ('20261016120000_application_adult_confirmed')
on conflict do nothing;
