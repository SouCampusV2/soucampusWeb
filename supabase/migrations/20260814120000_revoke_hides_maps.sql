-- Отзыв креаторства уносит карты человека с витрины.
--
-- Раньше отзыв закрывал только загрузку нового: уже опубликованные карты
-- продолжали продаваться, а снимать их приходилось по одной руками через
-- каталог. То есть у человека, которого лишили статуса за ворованные
-- работы, эти работы оставались на витрине до тех пор, пока владелец не
-- пройдёт по списку. Теперь снятие идёт одним действием вместе с
-- отзывом.
--
-- Возвращать их обратно тоже нужно скопом — когда статус выдадут снова, —
-- и вот тут важно НЕ задеть карты, снятые по своим отдельным причинам.
-- Поэтому третье значение hidden_by: 'revoked' говорит «эта карта ушла с
-- витрины не сама по себе, а вместе со статусом автора».
--
-- Значение, а не отдельная колонка-флаг: hidden_by и заведён затем, чтобы
-- отвечать на вопрос «кто снял», и ответов на него ровно три — автор,
-- модератор по этой карте, отзыв статуса. Флагом сбоку пришлось бы
-- держать два поля, из которых осмысленно всегда одно.

alter table public.products
  drop constraint if exists products_hidden_by_check;

alter table public.products
  add constraint products_hidden_by_check
  check (hidden_by is null or hidden_by in ('creator', 'moderator', 'revoked'));

comment on column public.products.hidden_by is
  'Кто убрал карту с витрины: creator — сам автор (может вернуть), '
  'moderator — снята по этой карте (вернёт только владелец сайта), '
  'revoked — ушла вместе с креаторством автора (вернётся, когда статус выдадут снова).';
