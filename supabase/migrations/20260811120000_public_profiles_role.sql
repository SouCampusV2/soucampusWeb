-- ------------------------------------------------------------
-- Роль в публичном профиле: креатор или обычный участник.
--
-- На /creator/<ник> до сих пор было не понять, кто перед тобой: у всех
-- одинаковая шапка, а разница между «человек выкладывает карты» и
-- «человек просто зарегистрирован» видна только по тому, пуст ли список
-- ниже. Пустой список у креатора без карт при этом выглядел ровно так
-- же, как профиль покупателя.
--
-- Флаг is_creator живёт в profiles с 24.07, но наружу не отдавался:
-- представление public_profiles заведено ровно затем, чтобы аноним
-- видел ПОДНАБОР колонок (см. 20260727130000_creators.sql — RLS
-- фильтрует строки, а не колонки). Добавляем колонку в этот поднабор.
--
-- Тайной is_creator не является: у креатора карты и так на витрине с
-- его именем. Личные поля (first_name/last_name/discord) в
-- представление по-прежнему не попадают.
--
-- create or replace view сохраняет и права (grant ниже — на всякий
-- случай, повторный безвреден), и security_invoker = false: запрос идёт
-- от владельца представления, поэтому RLS таблицы profiles его не
-- режет. Порядок колонок обязан совпадать со старым — replace не
-- разрешает переименование и перестановку существующих, только
-- добавление в конец.
-- ------------------------------------------------------------
create or replace view public.public_profiles
with (security_invoker = false) as
  select id, display_name, avatar_url, bio, is_verified, is_creator
  from public.profiles;

grant select on public.public_profiles to anon, authenticated;
