-- ============================================================
-- Покупатель получает ОДОБРЕННЫЙ файл, а не «тот, что лежит сейчас».
-- 2026-11-10, аудит безопасности, находки S-01 и S-02.
--
-- ЧТО БЫЛО. У карты одна колонка file_path, и читают её двое:
-- модератор (что смотреть) и скачивание (что отдавать покупателю).
-- Автор заменил файл у проданной карты — карта честно ушла в очередь,
-- но путь к новому файлу уже записан, и кнопка Download у всех, кто
-- карту взял, с этой секунды отдаёт файл, которого никто не смотрел.
-- Отклонили правку — путь всё равно новый. А прежний, одобренный файл
-- стирала уборка Storage: он больше нигде не был упомянут.
--
-- ЧТО МЕНЯЕТСЯ. Колонок две, и у каждой один читатель:
--   file_path           — заявка автора; её смотрит модератор;
--   approved_file_path  — то, что одобрено; его получает покупатель.
-- Вторую колонку пишет ТОЛЬКО база, в момент перехода pending → live
-- (триггер ниже). Ни автор, ни обработчик её не называют — значит, и
-- забыть или подделать её негде (инвариант 12: переходы знает база).
--
-- Плюс рубильник (S-02): file_blocked. Карта, снятая за вредное
-- содержимое, продолжала скачиваться у всех, кто её взял, — так велит
-- инвариант 13 («файл удалённой карты не удаляется»), и для обычного
-- снятия он верен. file_blocked — исключение из него, которое ставит
-- только админ: файл не отдаётся никому, пока флаг стоит.
--
-- ⚠️ СРОК: ДО ДЕПЛОЯ. Миграция только добавляет, старый код её не
-- замечает. Новый код читает approved_file_path при каждом скачивании:
-- задеплоишь раньше прогона — Download у всех отвечает ошибкой, пока
-- колонки нет. Сначала preview, потом прод (docs/RULES.md → «Миграции»).
-- ============================================================

alter table public.products
  add column if not exists approved_file_path text;

alter table public.products
  add column if not exists file_blocked boolean not null default false;

alter table public.products
  add column if not exists file_block_reason text;

comment on column public.products.approved_file_path is
  'Путь к файлу, который прошёл модерацию. Его получают покупатели. '
  'Пишет только триггер z_products_stamp_approved_file при pending → live.';

comment on column public.products.file_blocked is
  'Рубильник: файл не отдаётся никому, включая купивших. Ставит только админ.';

-- ------------------------------------------------------------
-- Заполнение задним числом.
--
-- Одобренным считаем нынешний файл у карт, которые сейчас НЕ в очереди
-- и хотя бы раз были на витрине. Заполняется только пустое — повторный
-- прогон ничего не перезапишет.
--
-- ⚠️ Чего здесь нет НАМЕРЕННО: карт в состоянии pending и rejected,
-- даже если они раньше были одобрены. У такой карты file_path — это
-- как раз новая, непросмотренная заявка (или отклонённая), а прежний
-- путь не сохранился. Назвать её одобренной значило бы узаконить ровно
-- то, что миграция закрывает. Цена: покупатели такой карты видят
-- «File coming soon», пока вы не одобрите заявку. Сколько таких карт —
-- запрос в конце файла.
--
-- ⚠️ Чего миграция узнать не может: был ли файл живой или спрятанной
-- карты подменён ДО 10.11 путём «спрятать → заменить → вернуть» (S-13).
-- Такие карты искать руками — checks.sql, раздел 13.
-- ------------------------------------------------------------
update public.products
   set approved_file_path = file_path
 where approved_file_path is null
   and file_path is not null
   and was_approved
   and state in ('live', 'hidden', 'suspended', 'deleted');

-- ------------------------------------------------------------
-- Одобрение запоминает файл.
--
-- Условие — именно переход pending → live: это единственная дорога, на
-- которой карту кто-то смотрел. hidden → live (автор вернул свою) и
-- suspended → live (админ снял претензию) файл НЕ переодобряют: там его
-- никто не открывал, и одобренным остаётся прежний.
--
-- INSERT сразу в live — это посев и ручная вставка админом из SQL:
-- обычная вставка всегда встаёт в pending (guard_product_insert и
-- createProduct).
--
-- Имя с «z_»: триггеры BEFORE идут по алфавиту, и этот обязан быть
-- последним — после b_products_author_edit, который может вернуть
-- state на место, и после products_guard_state, который может
-- отказать в переходе.
--
-- Триггер работает и под служебным ключом — в отличие от «сторожей»,
-- он не спрашивает про роль: он не запрещает, а записывает факт.
-- ------------------------------------------------------------
create or replace function public.stamp_approved_file()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.state = 'live' and (tg_op = 'INSERT' or old.state = 'pending') then
    new.approved_file_path := new.file_path;
  end if;
  return new;
end;
$$;

drop trigger if exists z_products_stamp_approved_file on public.products;
create trigger z_products_stamp_approved_file
  before insert or update on public.products
  for each row execute function public.stamp_approved_file();

notify pgrst, 'reload schema';

