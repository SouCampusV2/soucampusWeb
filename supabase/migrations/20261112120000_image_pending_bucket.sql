-- Закрытый бакет для картинок, ещё не прошедших проверку.
-- 2026-11-12, аудит безопасности, находка S-19.
--
-- ЧТО БЫЛО. Непроверенная картинка ложилась в тот же бакет, где живут
-- готовые (avatars, product-images, portfolio-images), под именем
-- pending-…. Эти бакеты публичные: файл по прямой ссылке открывается
-- всем и сразу. Проверки — тип, пересборка, антивирус — стоят в шаге
-- confirm, а до него дело могло не дойти: любой вошедший просил слот
-- на аватар, загружал что угодно и confirm не вызывал. Получался
-- бесплатный публичный хостинг под адресом нашего проекта, 150 файлов
-- в час с аккаунта, без уборки.
--
-- ЧТО МЕНЯЕТСЯ. Непроверенное ложится СЮДА — в бакет, которого снаружи
-- не видно. В публичный бакет картинку пишет только confirm, уже
-- пересобранной. Политик у бакета нет ни одной: загрузка идёт по
-- одноразовому токену, который выдаёт сервер, читает и удаляет только
-- служебный ключ.
--
-- Потолки — те же, что у публичных бакетов (миграция 20261101120000):
-- 10 МБ и четыре типа картинок. Тип при загрузке называет клиент, так
-- что это первый фильтр, а не проверка; проверяет confirm.
--
-- ⚠️ СРОК: ДО ДЕПЛОЯ. Новый код выдаёт токен на этот бакет: задеплоишь
-- раньше прогона — загрузка аватаров и картинок карт отвечает ошибкой,
-- пока бакета нет. Старый код о бакете не знает и работает как раньше.
-- Сначала preview, потом прод (docs/RULES.md → «Миграции»).
--
-- Хвосты. pending-файлы, оставшиеся в публичных бакетах от прежней
-- схемы, миграция НЕ трогает: удалять объекты Storage запросом SQL
-- нельзя — строка пропадёт, а сам файл останется лежать. Их убирает
-- `node scripts/sweep-pending.mjs` (сначала показывает, что нашёл).
-- ============================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'image-pending',
  'image-pending',
  false,
  10485760,
  array['image/png', 'image/jpeg', 'image/gif', 'image/webp']
)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

