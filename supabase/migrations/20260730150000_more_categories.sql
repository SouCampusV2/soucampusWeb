-- ============================================================
-- Больше категорий магазина — 2026-07-30.
--
-- В 20260730120000 колонка category принимала два значения (assets,
-- landscape) — ровно те вкладки, что были в навбаре. Для маркетплейса
-- этого мало: «спавн», «мини-игра» и «интерьер» — принципиально разные
-- вещи, которые покупатель ищет по-разному, а сейчас все они сваливались
-- бы в «assets».
--
-- «free» по-прежнему НЕ категория: бесплатность определяется ценой 0
-- (см. filterByCategory в src/lib/products.ts). Тег «free» у платной
-- карты был бы прямой ложью на витрине.
--
-- Правило миграций: сначала preview, потом прод (docs/RULES.md).
-- ============================================================

alter table public.products drop constraint if exists products_category_check;
alter table public.products add constraint products_category_check
  check (category in (
    'spawn',      -- спавны и хабы серверов
    'adventure',  -- приключенческие/RPG-карты
    'minigame',   -- мини-игры, PvP-арены
    'building',   -- отдельные постройки
    'interior',   -- интерьеры
    'landscape',  -- ландшафт, терраформинг
    'assets'      -- наборы блоков/деталей
  ));
