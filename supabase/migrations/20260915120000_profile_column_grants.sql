-- ============================================================
-- Профиль: браузер пишет только шесть колонок — 2026-09-15.
--
-- Шлюз записи, пути №7 и №8 (имя при первом входе, форма настроек).
-- Решение владельца 15.09: закрывать НЕ своим обработчиком, как карты, а
-- правами на колонки в самой базе. Разбор — docs/ARCHITECTURE.md § 5.4.
--
-- ------------------------------------------------------------
-- ПОЧЕМУ НЕ ШЛЮЗ, КАК У КАРТ
-- ------------------------------------------------------------
-- Шлюз пишет служебным ключом, а служебный ключ выключает триггеры.
-- У карт это стоило одной функции в TypeScript. У профиля — больше:
-- guard_username_change для служебной роли не просто молчит, а на любой
-- смене имени сразу запускает паузу. Бесплатное первое имя на /welcome
-- стало бы платным, и правила имени пришлось бы переписать и в
-- миграции, и в коде — то есть держать в двух местах.
--
-- А корень дыр 21.08 был не в том, что пишет браузер, а в том, ЧТО он
-- может писать: политика «own profile update» разрешает любую колонку
-- своей строки. Поэтому каждое новое поле-право было открыто всем, пока
-- ему не напишут отдельный триггер, — так вышло с is_verified и с паузой
-- на заявки. Правила при этом целиком выражаются базой, а план (§ 5.4,
-- шаг 5) прямо разрешает оставить такой путь без своего обработчика.
--
-- ------------------------------------------------------------
-- ЧТО ЭТА МИГРАЦИЯ МЕНЯЕТ
-- ------------------------------------------------------------
-- «Всё можно, кроме запрещённого» → «ничего нельзя, кроме разрешённого».
-- Право менять строку целиком у браузера отбирается, взамен выдаётся
-- право ровно на те колонки, которые пишут формы. Новая колонка отныне
-- закрыта ПО УМОЛЧАНИЮ, и помнить о её защите не нужно.
--
-- По дороге закрывается то, что не стерёг никто (найдено 15.09):
--   username_changed_at    — обнулялась из консоли, и пауза на смену
--                            имени снималась: триггер возвращает её
--                            только при смене самого имени;
--   creator_revoked_reason — причину отзыва статуса можно было
--   creator_revoked_at       переписать себе самому;
--   discord, created_at    — мелочь, но тоже не территория человека.
--
-- Триггеры на поля-права (protect_is_admin и соседи) НЕ удаляются: они
-- остаются вторым рубежом и отвечают тому, кто однажды выдаст колонку
-- снова. Разница в поведении видна снаружи: раньше запись is_admin
-- проходила и тихо откатывалась, теперь база отвечает отказом прав.
--
-- ------------------------------------------------------------
-- ПОРЯДОК: ЛЮБОЙ. Формы и так пишут только разрешённые колонки, код
-- менять не нужно. Сначала preview, потом прод (docs/RULES.md).
-- ============================================================

-- ------------------------------------------------------------
-- 1. Аватар — только наш. СТОИТ ПЕРВЫМ НАМЕРЕННО: проверка валидируется
--    на существующих строках, и если на какой-то базе лежит значение,
--    которого мы не предусмотрели, миграция упадёт ЗДЕСЬ — до того, как
--    тронет права. Упавший прогон лучше тихо сломанной формы.
--
-- Зачем. avatar_url показывается на профиле и под каждым комментарием
-- человека, то есть браузер каждого читателя идёт по этому адресу. Впиши
-- туда свой сервер — и собирай IP всех, кто открыл страницу. Та же дыра,
-- что закрыта для описаний карт и для фото из Google (RULES.md → «Чужие
-- сервисы»), и то же, что обещано в /privacy.
--
-- Три допустимых вида:
--   null                         — аватара нет;
--   наш Storage, СВОЯ папка      — так пишет форма настроек;
--   файл сайта ("/…") с галочкой — лого бренда (20260727130000). Без
--                                  галочки нельзя: иначе любой поставил
--                                  бы себе лого SouCampus.
--
-- ⚠️ Адреса проектов вписаны явно, а не шаблоном «любой supabase.co»:
-- иначе злоумышленник завёл бы СВОЙ проект с бакетом avatars и тем же
-- путём, и проверка пропустила бы его сервер. pogwmoyrpaxxwkwhzjcv —
-- прод (сверено 15.09 по коду, который отдаёт soucampus.online),
-- gmspmvnrzavxcbiqlhob — preview. Появится свой домен Storage или третий
-- проект — дописать сюда отдельной миграцией.
--
-- ⚠️ Следствие галочки, о котором надо знать: снять is_verified у
-- аккаунта с локальным аватаром не выйдет — строка перестанет проходить
-- проверку. Сначала сменить аватар, потом снимать галочку.
-- ------------------------------------------------------------
alter table public.profiles drop constraint if exists profiles_avatar_url_own;
alter table public.profiles
  add constraint profiles_avatar_url_own check (
    avatar_url is null
    or avatar_url ~ (
      '^https://(pogwmoyrpaxxwkwhzjcv|gmspmvnrzavxcbiqlhob)\.supabase\.co'
      || '/storage/v1/object/public/avatars/' || id::text || '/'
    )
    or (is_verified and avatar_url ~ '^/[^/]')
  );

-- ------------------------------------------------------------
-- 2. Права на колонки.
--
-- ⚠️ Отбирается ПРАВО ТАБЛИЦЫ, а выдаётся право КОЛОНОК — это два разных
-- уровня в Postgres, и второй без первого работает. Политика
-- «own profile update» остаётся: она решает, КАКУЮ СТРОКУ можно менять
-- (свою), а права колонок — КАКИЕ ПОЛЯ. Вместе они и есть правило.
--
-- Триггеры, дописывающие другие колонки (username_changed_at,
-- updated_at), при этом работают: право проверяется по тому, что
-- прислал запрос, а не по тому, что строка получила в итоге.
--
-- Служебный ключ (админка, модерация, шлюзы) не затрагивается: у
-- service_role свои права.
-- ------------------------------------------------------------
revoke update on table public.profiles from anon, authenticated;

grant update (username, first_name, last_name, bio, name_color, avatar_url)
  on table public.profiles to authenticated;

notify pgrst, 'reload schema';

