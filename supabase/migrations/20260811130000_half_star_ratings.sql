-- ------------------------------------------------------------
-- Половинки в оценках: 3.5 и 4.5, а не только целые.
--
-- Пять делений — грубая шкала. Разница между «хорошая карта» и «очень
-- хорошая» реально есть, а выразить её нечем: человек ставит 4 или 5 и
-- в обоих случаях чувствует, что соврал. Половинки дают десять делений,
-- дальше дробить смысла нет — 4.25 никто не различает.
--
-- Тип numeric(2,1), а не «хранить удвоенное целое»: во втором случае
-- каждое место, читающее оценку, обязано помнить про деление на два, и
-- рано или поздно одно из них забудет. В базе лежит ровно то число,
-- которое видит человек.
--
-- float здесь был бы ошибкой: 0.1 в двоичной дробью не представима, и
-- проверка `stars * 2 = round(stars * 2)` на нём иногда не сходится.
-- numeric — точная десятичная арифметика, для шага 0.5 это то, что надо.
--
-- Проверка ровно та же по границам (1..5) плюс требование кратности
-- половине: 3.7 по-прежнему не запишется.
-- ------------------------------------------------------------
alter table public.product_ratings
  drop constraint if exists product_ratings_stars_check;

alter table public.product_ratings
  alter column stars type numeric(2, 1) using stars::numeric(2, 1);

alter table public.product_ratings
  add constraint product_ratings_stars_check
  check (stars >= 0.5 and stars <= 5 and (stars * 2) = round(stars * 2));

