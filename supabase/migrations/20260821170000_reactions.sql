-- Реакция на карту — 2026-08-21.
--
-- КАК ЭТО УСТРОЕНО (решение владельца). У карты ОДНА реакция, и выбирает
-- её АВТОР при публикации — из списка, который владелец ведёт в базе.
-- Посетители по ней просто жмут, как по лайку. Не набор смайликов под
-- каждой картой, а один — тот, который автор считает подходящим своей
-- работе.
--
-- ПОЧЕМУ СПИСОК В БАЗЕ, А НЕ В КОДЕ — и это ОТЛИЧАЕТСЯ от палитры цвета
-- ника и словарей характеристик, которые лежат именно в коде. Разница в
-- том, кто и как часто правит. Цвет ника меняет разработчик раз в год
-- вместе с дизайном; список реакций владелец хочет пополнять сам, глядя
-- на живой сайт, — и требовать ради каждого смайлика деплой значит
-- гарантировать, что список никогда не пополнится. Строка в таблице
-- правится из Table Editor за десять секунд.
--
-- ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО: свободного ввода эмодзи. Ни у автора, ни у
-- посетителя. Всё, что показывается всем, должно быть выбрано из
-- заведомо безопасного набора — иначе это ввод пользователя, и его
-- пришлось бы проверять на длину, на количество символов, на
-- невидимые склейки. Выбор из списка снимает вопрос целиком.

-- ------------------------------------------------------------
-- 1. Список реакций.
--
-- Реакции станут КАРТИНКАМИ — «маленькими гифками, как в дискорде»
-- (решение владельца). Поэтому image_url заведён сразу, а не «когда
-- дойдёт»: иначе это была бы миграция схемы под живым сайтом ради того,
-- что уже известно. Заводить поля «на всякий случай» так же вредно, как
-- и всегда, — но здесь намерение названо, а не предположено.
--
-- Emoji при этом остаётся и не станет лишним: он — запасной вариант,
-- если картинка не загрузится, и подпись в списке выбора у автора.

create table if not exists public.reaction_options (
  id          uuid primary key default gen_random_uuid(),
  -- Сам символ. Один графический знак, но НЕ один символ Unicode:
  -- у эмодзи с модификаторами (цвет кожи, флаги, семьи) их несколько.
  -- Отсюда потолок в 16, а не в 1.
  emoji       text not null check (char_length(emoji) between 1 and 16),
  -- Подпись для средства чтения с экрана и для подсказки при наведении:
  -- смайлик сам по себе немой, и «нажать 🔥» без слова непонятно.
  label       text not null check (char_length(label) between 2 and 32),
  -- Картинка вместо символа — то, чем реакции станут («маленькие гифки,
  -- как в дискорде», решение владельца). Показывается вместо emoji,
  -- когда заполнена; emoji при этом остаётся запасным вариантом, если
  -- картинка не загрузится, и подписью в списке выбора.
  --
  -- Потолок 4096, а не 2048 как у обычных ссылок: сюда ляжет либо адрес
  -- в Storage (короткий), либо data:-URI маленькой картинки (длинный).
  image_url   text check (image_url is null or char_length(image_url) <= 4096),
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);

alter table public.reaction_options enable row level security;

-- Читают все: список нужен и автору в форме, и посетителю на странице.
create policy "public read reaction options"
  on public.reaction_options for select
  to anon, authenticated using (true);

-- Пишет только владелец — служебным ключом или из Table Editor. Политики
-- на запись нет вовсе, и это не забывчивость: нет политики — нет и права.

insert into public.reaction_options (emoji, label, sort_order) values
  ('🔥', 'Fire',      10),
  ('❤️', 'Love',      20),
  ('😮', 'Wow',       30),
  ('🏗️', 'Build',     40),
  ('🌲', 'Nature',    50),
  ('⚔️', 'Adventure', 60),
  ('🏰', 'Castle',    70),
  ('✨', 'Magic',     80)
on conflict do nothing;

-- Одна реакция С КАРТИНКОЙ — чтобы этот путь было видно и можно было
-- потрогать до того, как появятся настоящие гифки. Картинка встроена
-- прямо в строку (data:-URI), а не лежит файлом: у неё нет ни хоста,
-- который надо разрешать, ни файла, который надо не потерять.
--
-- Когда дойдёт до настоящих гифок, это будет ПРАВКА СТРОКИ из Table
-- Editor: залить файл в публичный бакет и вписать сюда его адрес. Ни
-- миграции, ни деплоя.
insert into public.reaction_options (emoji, label, image_url, sort_order) values
  ('💎', 'Diamond',
   'data:image/svg+xml;utf8,' ||
   '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">' ||
   '<path d="M6 3h12l4 6-10 12L2 9z" fill="%2338bdf8"/>' ||
   '<path d="M6 3h12l4 6H2z" fill="%237dd3fc"/></svg>',
   90)
on conflict do nothing;

-- ------------------------------------------------------------
-- 2. Какую реакцию выбрал автор.
--
-- on delete set null, а не cascade: удаление строки из списка реакций —
-- это «мы больше не предлагаем этот смайлик», а не «снести все карты,
-- которые его выбрали». Карта просто останется без реакции.

alter table public.products
  add column if not exists reaction_option_id uuid
  references public.reaction_options(id) on delete set null;

-- ------------------------------------------------------------
-- 3. Кто нажал.
--
-- Первичный ключ по паре (карта, человек) — и это ВСЯ защита от накрутки,
-- которая здесь нужна. Считать нажатия было бы неверно: реакция это «мне
-- нравится», а не «сколько раз я кликнул». Второе нажатие в UI снимает
-- своё — то есть delete, а не ещё одна строка.
--
-- Эмодзи в строке НЕ хранится: реакция у карты одна, и дублировать её у
-- каждого нажавшего значило бы завести второе место, где живёт ответ на
-- вопрос «какая тут реакция». Сменил автор смайлик — сменился у всех
-- нажавших, и это правильно: они реагировали на карту, а не на символ.

create table if not exists public.product_reactions (
  product_id uuid not null references public.products(id) on delete cascade,
  user_id    uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (product_id, user_id)
);

create index if not exists product_reactions_product_idx
  on public.product_reactions (product_id);

alter table public.product_reactions enable row level security;

-- Читают все: число под кнопкой видно и анониму. Отдаётся при этом не
-- «кто нажал», а количество — сама выборка идёт по product_id и
-- показывается числом (см. ReactionButton). Строка тут и так безобидна:
-- пара (карта, человек), никаких данных о человеке.
create policy "public read reactions"
  on public.product_reactions for select
  to anon, authenticated using (true);

-- Ставит и снимает только за себя.
--
-- РЕАГИРОВАТЬ МОЖЕТ ЛЮБОЙ ВОШЕДШИЙ, а не только скачавший, — в отличие
-- от оценок (там has_purchased) и будущих комментариев. Довод: оценка и
-- комментарий это СУЖДЕНИЕ о товаре, и оно чего-то стоит, только если
-- человек товар видел. Реакция — «понравилось, как выглядит», и для неё
-- достаточно посмотреть на скриншоты. Требовать покупку значило бы
-- получить ноль реакций у всех карт: реагируют до покупки, а не после.
create policy "insert own reaction"
  on public.product_reactions for insert
  to authenticated with check (auth.uid() = user_id);

create policy "delete own reaction"
  on public.product_reactions for delete
  to authenticated using (auth.uid() = user_id);

-- ------------------------------------------------------------
-- 4. Сколько нажатий — одним запросом.
--
-- Через функцию, а не count() из браузера: PostgREST умеет отдать
-- количество заголовком, но за КАЖДУЮ карту отдельным запросом, и на
-- витрине это превратилось бы в двадцать запросов на страницу.
--
-- security definer + фиксированный search_path — стандартная защита
-- таких функций; читает она всё равно только то, что и так открыто
-- политикой выше.

create or replace function public.get_reaction_counts(p_ids uuid[])
returns table (product_id uuid, reactions bigint)
language sql
security definer
set search_path = ''
as $$
  select r.product_id, count(*)::bigint
    from public.product_reactions r
   where r.product_id = any(p_ids)
   group by r.product_id;
$$;

grant execute on function public.get_reaction_counts(uuid[]) to anon, authenticated;

-- ------------------------------------------------------------
-- 5. Автор не должен уметь подменить чужие нажатия.
--
-- Выбор реакции — обычное поле карты, и правит его автор из браузера
-- (guard_product_author_edit). Само по себе это безопасно: сменить
-- смайлик не значит сменить число. Но добавить reaction_option_id в
-- перечень «полей, которые назначаем сами» НЕЛЬЗЯ — тогда автор не смог
-- бы его менять вовсе. Поэтому здесь ничего и не делается: поле
-- сознательно оставлено автору, и это запись «мы подумали», а не
-- пропуск.

notify pgrst, 'reload schema';
