-- ------------------------------------------------------------
-- 1. Снять все политики чтения — по свойству, а не по имени.
--
-- Урок 21.09 (social_gateway_fix): `drop policy if exists "имя"` молча
-- ничего не делает, если политику назвали иначе — руками в дашборде,
-- например. Поэтому снимаем всё, что осталось на таблице. Политик
-- записи там нет с 21.09, так что после цикла на таблице не остаётся
-- ни одной политики — это и есть проверяемое конечное состояние.
-- ------------------------------------------------------------
do $$
declare
  p record;
begin
  for p in
    select policyname
      from pg_policies
     where schemaname = 'public'
       and tablename = 'product_comments'
  loop
    raise notice 'Снимаю политику: product_comments.%', p.policyname;
    execute format('drop policy %I on public.product_comments', p.policyname);
  end loop;
end $$;

-- ------------------------------------------------------------
-- 2. И права на таблицу — тоже.
--
-- RLS без единой политики уже не отдаёт ни строки. Revoke — второй
-- рубеж и заодно ясный ответ: запрос в таблицу получает отказ прав
-- (42501), а не пустой список, который выглядит как «комментариев нет».
-- По той же причине, по которой так закрыта page_views.
--
-- Кому таблица остаётся доступна: служебному ключу (шлюз, админка) и
-- функциям security definer (soft_delete_comment*) — они работают с
-- правами владельца.
-- ------------------------------------------------------------
revoke all on public.product_comments from public, anon, authenticated;

notify pgrst, 'reload schema';

