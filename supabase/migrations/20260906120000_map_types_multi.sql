-- Тип карты: одно значение → набор до трёх.
--
-- Решение владельца 2026-09-06, по итогам прохода чек-листа.
--
-- ПОЧЕМУ ИЗМЕНИЛОСЬ. Колонка заводилась 21 августа с доводом «карта
-- бывает чем-то одним, в отличие от режимов и тем» — и довод оказался
-- неверен на живом каталоге: спавн с прилегающим городом честно является
-- и спавном, и городом, а приключенческая карта с аренами — и квестом, и
-- мини-игрой. Заставляя выбрать одно, мы заставляли автора соврать, а
-- покупателя — не найти карту по второму, столь же верному признаку.
--
-- ⚠️ ПОТОЛОК В ТРИ ЗНАЧЕНИЯ — ЭТО СМЫСЛ, А НЕ ЗАЩИТА ОТ ПЕРЕПОЛНЕНИЯ.
-- Карта, помеченная всеми восемью типами, не описана никак: тип перестаёт
-- отвечать на вопрос «что это» и превращается в способ попасть во все
-- фильтры разом. Три — это «основное и два уточнения». Отсюда же и место
-- запрета: он в базе, а не в форме, потому что запись идёт из браузера
-- напрямую и спрятанная кнопка не защищает ничего.
--
-- ПОРЯДОК ВЫКАТКИ: миграция ДОБАВЛЯЕТ колонку и не трогает старую, значит
-- идёт ДО деплоя. Старый код продолжает читать map_type и не ломается.
-- Снос map_type — отдельной миграцией ПОСЛЕ деплоя, когда никто её уже
-- не спрашивает. Тот же порядок, что у перевода состояния карты на
-- state (шаг 1 / шаг 2, 15-16 августа).

-- ------------------------------------------------------------
-- 1. Новая колонка.

alter table public.products
  add column if not exists map_types text[] not null default '{}';

-- ------------------------------------------------------------
-- 2. Переносим то, что уже проставлено.
--
-- Пустую строку и пробелы отбрасываем: в наборе они означали бы «тип
-- есть, и он никакой», а это хуже отсутствия.

update public.products
set map_types = array[map_type]
where map_type is not null
  and btrim(map_type) <> ''
  and cardinality(map_types) = 0;

-- ------------------------------------------------------------
-- 3. Потолок.
--
-- array_within уже есть (20260821130000): длина набора и длина каждой
-- строки в нём. Отдельным ограничением, а не дописыванием в
-- products_specs_len, — чтобы снос map_type позже не заставлял
-- пересобирать общее ограничение целиком.

alter table public.products
  drop constraint if exists products_map_types_len;

alter table public.products
  add constraint products_map_types_len
  check (public.array_within(map_types, 3, 32)) not valid;

-- ------------------------------------------------------------
-- 4. Индекс.
--
-- GIN, как у mc_versions и tags: вопрос тот же — «содержит ли набор
-- такое значение». По типу карты фильтруют из попапа фильтров, то есть
-- это чтение, которое действительно происходит.

create index if not exists products_map_types_idx
  on public.products using gin (map_types);

-- ------------------------------------------------------------
-- 5. Журнал прогонов — последней строкой (docs/RULES.md → «Миграции»).

insert into ops.applied_migrations (version)
values ('20260906120000_map_types_multi')
on conflict (version) do nothing;

notify pgrst, 'reload schema';
