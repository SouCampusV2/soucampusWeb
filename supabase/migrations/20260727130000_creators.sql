-- ============================================================
-- Мульти-креатор (2026-07-27): у каждого пользователя есть публичный
-- профиль, у каждого товара — автор.
--
-- До этой миграции магазин был одноэтажным: страница /creator/[username]
-- держала одного захардкоженного продавца, товары ни к кому не
-- привязаны, а профили закрыты RLS «только своя строка» — то есть чужой
-- профиль показать было физически нечем.
--
-- Правило миграций: СНАЧАЛА preview, ПОТОМ прод (docs/RULES.md).
-- ============================================================


-- ------------------------------------------------------------
-- 1. Публичные поля профиля
--
-- bio — текст «о себе» на странице креатора.
-- is_verified — та самая галочка. Ей же сейчас управляется единственная
--   привилегия витрины: кнопка «Order a custom build» показывается только
--   у verified-профиля (решение владельца: приём заказов пока только у
--   бренда). Если однажды это разъедется — завести отдельный флаг, а не
--   растягивать смысл этого.
--
-- is_creator (уже существует) НЕ используем как «показывать ли профиль»:
-- по решению владельца профиль есть у КАЖДОГО пользователя, просто у
-- кого-то без карт.
-- ------------------------------------------------------------
alter table public.profiles add column if not exists bio text;
alter table public.profiles add column if not exists is_verified boolean not null default false;


-- ------------------------------------------------------------
-- 2. Публичное чтение — через ПРЕДСТАВЛЕНИЕ, а не политику на таблице
--
-- Политика `for select using (true)` на самой profiles открыла бы строку
-- ЦЕЛИКОМ: RLS фильтрует строки, а не колонки, — и наружу уехали бы
-- first_name/last_name/discord. Поэтому публичный доступ даётся к
-- отдельному представлению, где перечислены ровно безопасные колонки.
--
-- security_invoker = false (умолчание, пишем явно ради читаемости):
-- представление выполняется с правами своего владельца и потому не
-- упирается в RLS-политику «только своя строка» у базовой таблицы.
-- Именно это и делает его публичным, оставляя саму profiles закрытой.
--
-- ⚠️ ПРАВИЛО НА БУДУЩЕЕ (разбор 2026-07-30, по предупреждению линтера
-- Supabase «Security Definer View»): здесь НИКОГДА не должно появиться
-- `select *`. Представление обходит RLS, поэтому со звёздочкой любая
-- новая приватная колонка в profiles автоматически и молча уехала бы в
-- публичный доступ. Колонки перечисляются явно — это и есть вся защита.
--
-- Само предупреждение линтера разобрано и принято осознанно: RLS
-- фильтрует СТРОКИ, а не колонки, поэтому политика `using(true)` на
-- самой таблице открыла бы и first_name/last_name/discord. Представление
-- — единственный прямой способ отдать наружу подмножество колонок.
-- ------------------------------------------------------------
create or replace view public.public_profiles
with (security_invoker = false) as
  select id, display_name, avatar_url, bio, is_verified
  from public.profiles;

grant select on public.public_profiles to anon, authenticated;


-- ------------------------------------------------------------
-- 3. Автор товара
--
-- on delete set null — удаление аккаунта не должно уносить с собой
-- проданные карты: заказы и файлы покупателей на них ссылаются. Товар
-- останется без автора, это чинится вручную.
-- ------------------------------------------------------------
alter table public.products
  add column if not exists creator_id uuid references public.profiles(id) on delete set null;

create index if not exists products_creator_idx on public.products (creator_id);


-- ------------------------------------------------------------
-- 4. Backfill: все существующие карты — на аккаунт SouCampus
--
-- Ищем по нику, а не по вписанному сюда UUID: id аккаунта на preview и на
-- проде РАЗНЫЕ, и захардкоженный uuid молча не совпал бы на одной из баз.
-- lower(display_name) — ник уникален регистронезависимо (см. индекс
-- profiles_display_name_lower_idx).
--
-- Если аккаунта с таким ником в этой базе нет, оба update просто ничего
-- не сделают — миграция не упадёт, но и привязки не будет. Проверить
-- после прогона: select count(*) from products where creator_id is null;
-- ------------------------------------------------------------
update public.products
set creator_id = (
  select id from public.profiles where lower(display_name) = 'soucampus' limit 1
)
where creator_id is null;

-- Бренду — галочка, фирменное написание ника, лого и текст «о себе».
--
-- Раньше всё это было захардкожено в page.tsx; теперь страница читает
-- данные из БД, поэтому наполняем их здесь — иначе профиль SouCampus
-- открылся бы с ником в том регистре, в каком его когда-то ввели, без
-- аватара и без биографии.
--
-- display_name = 'SouCampus' — именно фирменное написание. На адрес это
-- не влияет: хэндл считается как lower(display_name), то есть
-- /creator/soucampus остаётся тем же. Уникальный индекс тоже по
-- lower(...), так что смена одного регистра ни с кем не конфликтует.
--
-- avatar_url — путь к файлу в public/, а не в Storage: это лого сайта,
-- лежащее в репозитории. Обычные пользователи грузят аватар через
-- /profile/edit, и туда попадает ссылка на Supabase Storage.
--
-- coalesce у bio/avatar_url — чтобы повторный прогон не затирал то, что
-- владелец успел поменять руками через /profile/edit.
update public.profiles
set is_verified = true,
    display_name = 'SouCampus',
    avatar_url = coalesce(avatar_url, '/logoSouCampus.png'),
    bio = coalesce(
      bio,
      'Custom Minecraft maps, structures and worlds — built on commission and sold ready-made. Spawns, RPG maps, cities, cathedrals and more.'
    )
where lower(display_name) = 'soucampus';
