-- ============================================================
-- Журнал модерации знает блокировку файла. 2026-11-12, аудит, S-02.
--
-- У колонки moderation_log.action — закрытый список значений. В админке
-- появились два новых действия: block_file и unblock_file (кнопка «Block
-- file» в каталоге). Без этой миграции сама блокировка работает, а
-- запись о ней в журнал отклоняет ограничение — то есть самое тяжёлое
-- действие модерации (отнять файл у заплативших) не оставляло бы следа.
--
-- Заодно в список добавлены hide и unhide. Обработчик каталога пишет их
-- в журнал с самого начала, и всё это время ограничение их молча
-- отклоняло: ошибка уходила только в лог сервера. Это не новое
-- поведение, а починка старого пробела, найденного попутно.
--
-- ⚠️ СРОК: неважно, до деплоя или после. До прогона новый код блокирует
-- файл, но не записывает это в журнал. Только расширяет список — старые
-- строки ему уже соответствуют. Сначала preview, потом прод
-- (docs/RULES.md → «Миграции»).
-- ============================================================

alter table public.moderation_log
  drop constraint if exists moderation_log_action_check;

alter table public.moderation_log
  add constraint moderation_log_action_check check (action in (
    'approve', 'reject', 'suspend', 'unsuspend', 'delete', 'restore',
    'hide', 'unhide',
    'block_file', 'unblock_file'
  ));

-- ------------------------------------------------------------
-- Проверка после прогона (только чтение, запустить отдельно):
--
--   -- В определении ограничения есть block_file и hide.
--   select pg_get_constraintdef(oid) from pg_constraint
--    where conname = 'moderation_log_action_check';
-- ------------------------------------------------------------

insert into ops.applied_migrations (version)
values ('20261112150000_moderation_log_file_actions')
on conflict (version) do nothing;
