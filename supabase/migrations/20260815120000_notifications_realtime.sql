-- Уведомления приходят сами — 2026-08-15.
--
-- Замечание владельца: «уведомление не приходит, пока я не обновлю сайт
-- или не перейду на другую страницу». Так и было — и это не баг в коде, а
-- отсутствующий кусок архитектуры. До сих пор про новое уведомление
-- узнавали только двумя способами: колокол считал непрочитанные при
-- монтировании и при смене адреса, а страница /notifications — при своём
-- серверном рендере. Оба способа требуют, чтобы человек что-то СДЕЛАЛ.
-- Пока он просто смотрит в открытую вкладку, никто ему ничего не скажет.
--
-- Правильный способ — не опрашивать сервер, а подписаться на событие.
-- У Supabase это Realtime: постоянное WebSocket-соединение, по которому
-- база сама шлёт браузеру факт вставки строки.
--
-- Почему Postgres Changes, а не Broadcast from Database (у Supabase их
-- два, и в документации по умолчанию советуют второй):
--
--   * Broadcast нужен на масштабе. Postgres Changes проверяет RLS ОТДЕЛЬНО
--     для каждого подписчика — на одну вставку при ста подписчиках сто
--     проверок, и обрабатывается это одним потоком, ради сохранения
--     порядка. Порог, с которого Supabase советует уходить на Broadcast, —
--     ~3000 одновременных подписчиков на одни и те же изменения. У нас
--     аккаунтов пока десятки, и подписан каждый на СВОИ строки.
--   * Broadcast — это отдельный триггер, отдельная тема канала, отдельная
--     политика на realtime.messages и своя модель доступа, которую надо
--     держать в согласии с уже написанной RLS notifications.
--   * Postgres Changes переиспользует ровно ту политику, что уже есть
--     ("read own notifications", см. 20260810120000): чужую строку
--     подписчику не пришлют по той же причине, по которой он не может её
--     прочитать запросом. Одна модель доступа вместо двух.
--
-- То есть здесь сознательно выбран более простой из двух механизмов,
-- потому что ограничение, ради которого существует сложный, у нас
-- наступит не скоро. Когда наступит — менять придётся эту миграцию и
-- подписку в браузере, серверный код уведомлений не трогается вовсе.
--
-- Правило миграций: сначала preview, потом прод (docs/RULES.md).
-- ============================================================

-- Публикация supabase_realtime — это список таблиц, изменения которых
-- Realtime вообще читает из WAL. Пока таблицы в нём нет, подписка в
-- браузере молча подключится и не получит ни одного события.
--
-- alter publication ... add table на уже добавленной таблице падает с
-- ошибкой, а миграция обязана переживать повторный прогон (и на preview,
-- и на проде она пойдёт по одному и тому же пути) — отсюда проверка.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end
$$;

-- replica identity не трогаем намеренно. full нужен только для того,
-- чтобы фильтровать события DELETE и видеть в них старую строку, — а
-- браузер подписан на INSERT (пришло новое) и UPDATE (прочитано в другой
-- вкладке). Ставить full значит писать в WAL всю строку на каждое
-- изменение, то есть платить за то, чем не пользуемся.
