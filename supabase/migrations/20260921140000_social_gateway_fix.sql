-- ------------------------------------------------------------
-- 1. `revoke ... from authenticated` НЕ ЗАКРЫВАЕТ ФУНКЦИЮ
-- ------------------------------------------------------------
-- `soft_delete_comment` осталась вызываемой из браузера. Причина — то
-- самое правило, которое в этом проекте записано трижды и которое я в
-- 20260921130000 сам же и нарушил: **Postgres выдаёт `execute` роли
-- PUBLIC по умолчанию**. Миграция 21.08 выдала грант `authenticated`
-- ПОВЕРХ дефолтного PUBLIC, а сняли вчера только его — дефолтный
-- остался, и `authenticated` продолжает попадать под PUBLIC.
--
-- ⚠️ Мораль сильнее самого бага: **снимать надо ту роль, которой
-- выдано, И PUBLIC — всегда.** В новых функциях
-- (20260921120000) это сделано правильно, три строки подряд
-- (`from public`, `from anon, authenticated`, `grant ... to
-- service_role`) — и именно эти две проверки в check:guards зелёные.
-- Отличие ровно одно: там revoke от PUBLIC был, здесь нет.
--
-- ------------------------------------------------------------
-- 2. ПОЛИТИКИ, КОТОРЫХ НЕТ ПОД ТЕМИ ИМЕНАМИ
-- ------------------------------------------------------------
-- `drop policy if exists "avatars insert own"` — и картинки с аватаром
-- по-прежнему грузятся из браузера. `if exists` означает, что политики
-- с ТАКИМ ИМЕНЕМ нет: `drop` молча ничего не сделал и ошибки не дал.
-- Значит запись разрешает политика, названная иначе, — скорее всего
-- созданная руками в дашборде (Supabase даёт им имена вида
-- «Give users access to own folder 1oj01fe_0»), а не нашей миграцией
-- 20260724150000. То же с `insert own reaction`.
--
-- ⚠️ **Урок про имена:** `drop policy if exists` по имени — это
-- утверждение «я знаю, как она называется». Если знание неверно,
-- миграция отчитывается успехом, ничего не сделав. Это тот же класс
-- ошибки, что зонды-выдумки 20.08 («revoke_hides_maps» вообще не
-- создаёт триггера) — только дороже: там врал зонд, здесь врала
-- миграция.
--
-- Поэтому ниже **не имена, а свойство**: снять ВСЕ политики на запись,
-- как бы они ни звались. Конечное состояние называется словами —
-- «из браузера в эти таблицы и бакеты не пишет никто», — и код ниже
-- приводит базу ровно к нему, а не к списку известных мне имён.
--
-- Политики на ЧТЕНИЕ не трогаются: `cmd <> 'SELECT'`. Картинки должны
-- показываться всем, комментарии и оценки — читаться.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Функция удаления комментария — закрыть по-настоящему.
-- ------------------------------------------------------------
revoke all on function public.soft_delete_comment(uuid) from public;
revoke all on function public.soft_delete_comment(uuid) from anon, authenticated;
grant execute on function public.soft_delete_comment(uuid) to service_role;

-- ------------------------------------------------------------
-- 2. Storage: ни одной политики на запись ни в одном бакете.
--
-- Все три бакета (product-files, product-images, avatars) пишутся
-- только через шлюз, и разрешает запись одноразовый токен от сервера
-- (createSignedUploadUrl), а не политика. Значит верное состояние —
-- ноль политик на запись, и перечислять бакеты незачем.
--
-- ⚠️ storage.objects принадлежит роли supabase_storage_admin. Если у
-- роли, которой прогоняют миграцию, не хватит прав, drop упадёт — и
-- пусть падает ГРОМКО: тихий пропуск здесь и есть та болезнь, которую
-- мы лечим. Имя политики при этом будет названо в ошибке, и её можно
-- снять руками в дашборде (Storage → Policies).
-- ------------------------------------------------------------
do $$
declare
  p record;
begin
  for p in
    select policyname
      from pg_policies
     where schemaname = 'storage'
       and tablename = 'objects'
       and cmd <> 'SELECT'
  loop
    raise notice 'Снимаю политику записи в Storage: %', p.policyname;
    execute format('drop policy %I on storage.objects', p.policyname);
  end loop;
end $$;

-- ------------------------------------------------------------
-- 3. Таблицы откликов и уведомлений: то же свойство.
--
-- Четыре таблицы, в которые из браузера больше не пишут. Читают —
-- по-прежнему из браузера, поэтому SELECT не трогаем.
-- ------------------------------------------------------------
do $$
declare
  p record;
begin
  for p in
    select tablename, policyname
      from pg_policies
     where schemaname = 'public'
       and tablename in (
         'product_comments',
         'product_ratings',
         'product_reactions',
         'notifications'
       )
       and cmd <> 'SELECT'
  loop
    raise notice 'Снимаю политику записи: %.%', p.tablename, p.policyname;
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;

notify pgrst, 'reload schema';

