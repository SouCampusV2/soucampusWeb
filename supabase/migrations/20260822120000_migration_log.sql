-- Прогон миграции оставляет след — 2026-08-22.
--
-- ЗАЧЕМ. CLI Supabase в проекте не заведён (нет supabase/config.toml):
-- миграции прогоняются руками в SQL-редакторе. Такой прогон не оставляет
-- следа НИГДЕ — ни в git (там лежит файл, а не факт его исполнения), ни в
-- самой базе. Поэтому вопрос «что уже на проде» до сегодня отвечался
-- памятью, а память врала: 22.08 выяснилось, что 20260821160000 числилась
-- ожидающей в двух документах, а на проде была прогнана.
--
-- ПОЧЕМУ НЕ СПИСОК В ДОКУМЕНТАЦИИ. Список — это КОПИЯ правды, и копии
-- расходятся с оригиналом. Список у нас был, его вели, он всё равно
-- соврал. Завести второй такой же значило бы добавить не проверку, а ещё
-- одну вещь, которую надо не забыть обновить.
--
-- КАК ТЕПЕРЬ. Запись делает сам прогон. Каждый файл миграции
-- ЗАКАНЧИВАЕТСЯ строкой, вписывающей себя в этот журнал. Соврать журнал
-- не может: строка появляется ровно тогда, когда код выполнился в этой
-- базе.
--
-- ⚠️ ПОЧЕМУ ИМЕННО В КОНЦЕ ФАЙЛА, а не в начале. Это работает в обе
-- стороны, как бы редактор ни исполнял файл. Гонит транзакцией — упавший
-- прогон откатит и запись. Гонит по одному запросу — выполнение просто
-- остановится на упавшем месте и до insert'а не дойдёт. Наполовину
-- прогнанная миграция не пометится прогнанной ни при каком раскладе.
--
-- ⚠️ ЖУРНАЛ НАЧИНАЕТСЯ С ЭТОЙ МИГРАЦИИ И НЕ ЗНАЕТ О ПРОШЛОМ. Задним
-- числом он не заполняется намеренно: вписать «прогнано» по памяти —
-- это ровно та болезнь, от которой журнал заводится. Всё, что старше
-- 20260822120000, прогнано на ОБЕИХ базах — проверено запросом-зондом
-- 2026-08-22 (прод и preview, девять зондов из девяти true).

-- ------------------------------------------------------------
-- 1. Отдельная схема, а не public.
--
-- PostgREST отдаёт наружу схему public: таблица там стала бы endpoint'ом
-- ещё до того, как мы решим, нужен ли он. RLS без политик вернул бы ноль
-- строк, но сам факт существования таблицы виден. Схема ops в
-- «Exposed schemas» не перечислена, поэтому из браузера её нет вовсе.
--
-- Приложение в этот журнал не ходит и ходить не должно: он для человека
-- в SQL-редакторе, а не для сайта.

create schema if not exists ops;

create table if not exists ops.applied_migrations (
  -- Имя файла без .sql — то, по чему миграции сортируются и называются
  -- везде: в git, в документации, в разговоре.
  version text primary key,
  applied_at timestamptz not null default now()
);

comment on table ops.applied_migrations is
  'Журнал прогонов. Пишет себя каждая миграция последней строкой. Заполнять руками нельзя — смысл в том, что запись делает сам прогон.';

-- ------------------------------------------------------------
-- 2. Закрыто, хотя снаружи и так не видно.
--
-- ⚠️ ЗАЧЕМ RLS, ЕСЛИ СХЕМА НЕ ВЫСТАВЛЕНА НАРУЖУ. Затем, что «не
-- выставлена» — это НАСТРОЙКА ПРОЕКТА (Exposed schemas в дашборде), а не
-- свойство базы. Настройку меняют галочкой, и в тот день таблица
-- окажется открытой, а про эту строку никто не вспомнит. Защита,
-- живущая в чужих настройках, — не защита.
--
-- Политик нет ни одной, и это не забывчивость: включённый RLS без
-- политик означает «никому», а не «всем». Тот же приём и тот же довод,
-- что у page_views (20260720200000) — туда браузер тоже не ходит
-- никогда, и она всё равно закрыта.
--
-- Прогон при этом не ломается: владелец таблицы (postgres, под которым
-- работает SQL-редактор) RLS обходит по умолчанию, service_role — по
-- атрибуту BYPASSRLS. То есть insert в самом низу файла проходит.

alter table ops.applied_migrations enable row level security;

-- Явный отзыв прав, хотя новая схема их никому и не выдаёт. Строка
-- нужна не базе, а читателю: она делает намерение проверяемым, а не
-- подразумеваемым. Если однажды в проекте появятся общие default
-- privileges, эта строка окажется единственным, что их переживёт.

revoke all on schema ops from public, anon, authenticated;
revoke all on ops.applied_migrations from public, anon, authenticated;

-- ------------------------------------------------------------
-- 3. Как теперь спрашивать «что прогнано в этой базе».
--
--   select version, applied_at from ops.applied_migrations order by version;
--
-- Сравнить с `ls supabase/migrations/`. Всё, что в файлах есть, а в
-- журнале нет и датировано ПОЗЖЕ 20260822120000, — не прогнано здесь.
-- Ничего сочинять под каждую миграцию больше не надо.

-- ------------------------------------------------------------
-- 4. Эта миграция записывает себя — как и все следующие.
--
-- on conflict do nothing, потому что миграции у нас пишутся
-- перезапускаемыми (docs/RULES.md → «Миграции»): повторный прогон файла
-- не должен падать на дубликате первичного ключа.

insert into ops.applied_migrations (version) values ('20260822120000_migration_log')
on conflict do nothing;
