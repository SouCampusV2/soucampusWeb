-- Шлюз записи, путь №1: файл карты больше не пишется из браузера.
-- 2026-09-11.
--
-- Это ДОКАЗАТЕЛЬСТВО, а не уборка (docs/ARCHITECTURE.md § 5.4, шаг 3).
-- Пока политика на запись жива, путь не мигрирован, чей бы код ни
-- вызывался: браузер по-прежнему может писать в бакет напрямую, просто
-- наши формы этого больше не делают. «Наш код так не делает» — не
-- защита; защита — снятая политика, и её видно запросом.
--
-- ⚠️ ПОРЯДОК: эта миграция УДАЛЯЕТ разрешение, значит идёт ПОСЛЕ
-- деплоя кода (docs/RULES.md → «Миграции»). Прогнать её раньше — это
-- сломать загрузку карт на проде: старый код на Vercel ещё пишет
-- напрямую, а политики уже нет.
--
-- Что встаёт на место политики: обработчик /api/creator/upload. Он
-- проверяет права (is_creator), лимит частоты, размер и расширение,
-- САМ строит путь в бакете и выдаёт одноразовый токен на этот путь
-- (createSignedUploadUrl служебным ключом). Служебный ключ RLS
-- обходит — поэтому снятая политика не мешает шлюзу, а закрывает всех
-- остальных.
--
-- После прогона осмысленны два зонда (оба через SQL-редактор):
--
--   select count(*) from pg_policies
--    where schemaname = 'storage' and tablename = 'objects'
--      and policyname = 'product-files insert own folder';
--   -- ждём 0
--
-- и живая проверка: в консоли браузера, будучи вошедшим креатором,
--   await supabase.storage.from('product-files').upload('<свой uid>/x.zip', new Blob(['x']))
--   -- ждём ошибку прав, а не успех.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Снять запись в product-files для обычных пользователей.
--
-- Политика заведена миграцией 20260730120000 и всё это время была
-- ЕДИНСТВЕННЫМ, что стояло между загружающим и бакетом: она проверяла
-- ровно один факт — свой ли первый сегмент пути. Ни размера, ни
-- расширения, ни содержимого файла база не знает и знать не может, а
-- всё это раздаётся покупателям под нашим брендом.
--
-- Чтения не трогаем: их у этого бакета и нет — он приватный, файл
-- выдаётся подписанной ссылкой из orders.ts после покупки. Это тот
-- самый шаг 4 плана: чтения не переносятся никогда.
-- ------------------------------------------------------------
drop policy if exists "product-files insert own folder" on storage.objects;

-- ------------------------------------------------------------
-- 2. product-images и avatars остаются как были — и это решение, а не
-- недосмотр.
--
-- Граница переезда проведена ПО БАКЕТУ, потому что доказательством
-- служит снятая политика, а снять половину политики нельзя. Картинки
-- галереи и описания живут в своём бакете, со своей политикой и своей
-- ценой ошибки (их видит каждый посетитель страницы карты, но они не
-- уезжают покупателю файлом) — это отдельная задача из той же очереди
-- § 5.4, и у неё будет своя миграция.
-- ------------------------------------------------------------

-- ------------------------------------------------------------
-- 3. Журнал прогонов — последней строкой (docs/RULES.md → «Миграции»).
-- ------------------------------------------------------------
insert into ops.applied_migrations (version)
values ('20260911120000_map_file_gateway')
on conflict (version) do nothing;

notify pgrst, 'reload schema';
