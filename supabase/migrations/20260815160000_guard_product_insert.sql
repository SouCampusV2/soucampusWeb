-- ============================================================
-- Новая карта всегда начинается с очереди — 2026-08-15.
--
-- Найдено при разборе на безопасность по просьбе владельца. Дыра НЕ
-- сегодняшняя: она существовала с тех пор, как креаторам разрешили
-- загрузку, и переезд на state её лишь не закрыл.
--
-- Что было. Публикацию у нас стережёт триггер guard_product_publication,
-- но он объявлен `before update`. На ВСТАВКУ не смотрел никто:
-- политика "creators insert own products" (миграция 20260811160000)
-- проверяет автора, статус креатора и паузу на заявки — и ни слова о
-- том, в каком состоянии карта создаётся.
--
-- Чем это грозило. Форма загрузки ходит через наш сервер, но политика
-- разрешает вставку и напрямую: сессия и публичный ключ лежат у
-- креатора в браузере, и запрос в PostgREST руками — дело одной
-- команды. Указав state = 'live' (а раньше is_published = true и
-- status = 'published'), автор выкладывал карту на витрину МИМО
-- модерации. Файл при этом раздаётся покупателям под нашим брендом —
-- то есть цена дыры не «некрасивая карточка», а что угодно в zip'е.
--
-- Почему триггером, а не политикой. Политику пришлось бы дописывать
-- условием на каждую колонку состояния, и она молча разошлась бы с
-- набором значений при следующей правке. Триггер же не проверяет
-- присланное, а НАЗНАЧАЕТ правильное: что бы ни пришло, новая карта
-- встаёт в очередь. Обойти это нельзя, не имея служебного ключа.
--
-- Правило миграций: сначала preview, потом прод (docs/RULES.md).
-- ============================================================

create or replace function public.guard_product_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Служебная роль и миграции — без ограничений: через них идут наш
  -- сервер (загрузка, модерация) и перенос данных.
  if not (auth.role() = 'authenticated' and auth.uid() is not null) then
    return new;
  end if;

  -- Всё, что решает судьбу карты, назначаем сами. Присланные значения
  -- не проверяем, а перезаписываем — так не нужно перечислять способы
  -- соврать.
  new.state := 'pending';
  new.submission_kind := 'first';
  new.deleted_by := null;
  new.was_approved := false;
  new.suspension_reason := null;
  new.rejection_reason := null;
  new.rejection_flags := '{}';

  -- Автор — тот, кто вставляет. Политика это и так проверяет, но пусть
  -- значение задаётся в одном месте с остальными.
  new.creator_id := auth.uid();

  return new;
end;
$$;

-- Имя с 'a', чтобы отработать ДО products_guard_state и
-- products_sync_legacy_flags: те считают производные от state, и к их
-- моменту state обязан быть уже правильным.
drop trigger if exists a_products_guard_insert on public.products;
create trigger a_products_guard_insert
  before insert on public.products
  for each row execute function public.guard_product_insert();
