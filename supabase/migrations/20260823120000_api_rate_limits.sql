--
-- ПОЧЕМУ ЭТО НЕ ДУБЛИРУЕТ 20260822130000. Тот триггер стоит на таблицах и
-- ловит запись откуда угодно. Этот счётчик стоит на ДЕЙСТВИИ обработчика,
-- у которого своей таблицы может не быть вовсе: «создать сессию Stripe» и
-- «разослать уведомление всем» ничего в считаемую таблицу не пишут.
--
-- ⚠️ ПОЧЕМУ НЕ ПАМЯТЬ ПРОЦЕССА (Map в модуле). Так делают в туториалах, и
-- на Vercel это не работает по двум причинам сразу: (1) обработчики живут
-- в НЕСКОЛЬКИХ параллельных инстансах, у каждого свой Map — значит и свой
-- полный лимит; (2) инстанс засыпает и стартует холодным, обнуляя счёт.
-- Лимит, который сбрасывается сам, — это не лимит, а его изображение.
-- Redis в проекте нет, заводить его ради пяти роутов дороже, чем таблица.
--
-- ⚠️ ПОЧЕМУ НЕ moderation_log, как предполагалось в плане. Он пишется
-- ДВУМЯ роутами из пяти (catalog, applications) и не знает про announce,
-- comments и moderation. Считать по журналу, который не видит три двери из
-- пяти, — это лимит с дырами. Плюс его строка привязана к product_id, а у
-- рассылки товара нет.

-- ------------------------------------------------------------
-- 1. Где живёт счёт.
--
-- Схема ops, а не public: это служебная таблица, сайту она не нужна ни на
-- чтение, ни на запись — в неё ходит только наш сервер под служебным
-- ключом. Тот же довод, что у ops.applied_migrations (20260822120000).
--
-- Строка = одно совершённое действие. Не «счётчик со сбросом», а журнал
-- событий: скользящее окно («сколько за последний час») считается только
-- так. Счётчик с обнулением в начале часа даёт известную дыру — двойной
-- лимит на стыке: полный расход в 10:59 и ещё один полный в 11:01.

create table if not exists ops.rate_events (
  id bigserial primary key,
  -- Что именно сделали: 'checkout', 'admin-announce' и т.п. Список живёт
  -- в коде (src/lib/rate-limit.ts), а не здесь: база стережёт объём и
  -- скорость, код решает, какие бывают действия. Тот же раздел
  -- обязанностей, что у характеристик карт (product-specs.ts).
  bucket text not null,
  -- Кто сделал. Всегда id аккаунта: все пять обработчиков и так требуют
  -- входа, так что считать по IP было бы шагом назад — один человек
  -- меняет адрес легче, чем аккаунт.
  actor text not null,
  created_at timestamptz not null default now()
);

-- Порядок колонок не случаен, как и в 20260822130000: сначала два точных
-- совпадения, потом диапазон по времени. Индекс с диапазоном впереди
-- обрывается на первой же колонке и дальше не помогает.
create index if not exists rate_events_actor_idx
  on ops.rate_events (bucket, actor, created_at desc);

-- Отдельный индекс под общую уборку (пункт 3): она ищет по одному только
-- времени, не зная ни bucket, ни actor, и верхним индексом
-- воспользоваться не может.
create index if not exists rate_events_created_idx
  on ops.rate_events (created_at);

alter table ops.rate_events enable row level security;

-- Политик нет ни одной — это значит «никому», а не «всем». Тот же приём,
-- что у page_views и applied_migrations. Служебный ключ проходит по
-- атрибуту BYPASSRLS, владелец таблицы — по умолчанию.
revoke all on ops.rate_events from public, anon, authenticated;
revoke all on sequence ops.rate_events_id_seq from public, anon, authenticated;

comment on table ops.rate_events is
  'Журнал действий для скользящих лимитов на /api/*. Пишется только через public.consume_rate_limit.';

-- ------------------------------------------------------------
-- 2. Одна функция вместо «прочитал, посчитал, вставил» в коде.
--
-- ПОЧЕМУ В БАЗЕ, А НЕ ТРЕМЯ ЗАПРОСАМИ ИЗ NODE. Между «посчитал» и
-- «вставил» есть зазор, и в него влезает второй запрос того же человека:
-- оба видят «использовано 9 из 10», оба вставляют, получается 11. По сети
-- этот зазор — десятки миллисекунд, то есть попадать в него будут не
-- только злоумышленники, но и обычные двойные клики. Здесь всё происходит
-- внутри одного вызова, а pg_advisory_xact_lock ниже выстраивает
-- одновременные вызовы одного и того же человека в очередь.
--
-- ⚠️ ФУНКЦИЯ ЛЕЖИТ В public, ХОТЯ ТАБЛИЦА В ops. Иначе её не вызвать:
-- PostgREST (через него ходит supabase-js .rpc()) отдаёт наружу только
-- выставленные схемы, а ops не выставлена и выставляться не должна.
-- Значит функция обязана быть в public — и значит её надо ЗАКРЫТЬ руками:
-- Postgres выдаёт execute на новую функцию роли PUBLIC по умолчанию, то
-- есть без revoke ниже любой посетитель сайта смог бы вызвать её из
-- консоли браузера и засорить таблицу. Ровно то правило, которое за
-- 20–21 августа выяснялось пять раз: запрет ставится там, где стоит
-- разрешение, — а здесь разрешение выдаётся само, молча.
--
-- ВОЗВРАЩАЕТ ЧИСЛО СЕКУНД, а не «да/нет»: 0 — можно, больше нуля —
-- сколько ждать. Ответу 429 нужен заголовок Retry-After, и считать его
-- второй раз на стороне Node значило бы завести второе место, где живёт
-- длина окна.

create or replace function public.consume_rate_limit(
  p_bucket text,
  p_actor text,
  p_limit int,
  p_window_seconds int
) returns int
language plpgsql
security definer
set search_path = ops, public, pg_temp
as $fn$
declare
  v_window constant interval := make_interval(secs => p_window_seconds);
  v_since  timestamptz := now() - v_window;
  v_used   int;
  v_oldest timestamptz;
begin
  if p_bucket is null or p_actor is null or p_limit is null or p_limit < 1 then
    raise exception 'consume_rate_limit: bad arguments';
  end if;

  -- Очередь из одновременных вызовов ОДНОГО человека. Замок берётся на
  -- транзакцию и отпускается сам; чужие пары (bucket, actor) друг друга
  -- не ждут, потому что ключ замка считается от них.
  perform pg_advisory_xact_lock(hashtextextended(p_bucket || ':' || p_actor, 0));

  -- Свои протухшие строки убираем сразу: по индексу это дёшево, и
  -- благодаря этому у активного человека в таблице лежит только живое
  -- окно, а не вся его история.
  delete from ops.rate_events
   where bucket = p_bucket and actor = p_actor and created_at < v_since;

  -- Уборка за теми, кто не вернулся (пункт 3).
  if random() < 0.01 then
    delete from ops.rate_events where created_at < now() - interval '1 day';
  end if;

  select count(*), min(created_at)
    into v_used, v_oldest
    from ops.rate_events
   where bucket = p_bucket and actor = p_actor and created_at >= v_since;

  if v_used >= p_limit then
    -- Слот освободится, когда САМАЯ СТАРАЯ запись выпадет из окна.
    -- greatest(1, …) — чтобы Retry-After никогда не был нулём: ответ
    -- «подожди 0 секунд» клиент читает как «можно прямо сейчас».
    return greatest(1, ceil(extract(epoch from (v_oldest + v_window - now())))::int);
  end if;

  insert into ops.rate_events (bucket, actor) values (p_bucket, p_actor);
  return 0;
end;
$fn$;

revoke all on function public.consume_rate_limit(text, text, int, int)
  from public, anon, authenticated;
grant execute on function public.consume_rate_limit(text, text, int, int)
  to service_role;

-- ------------------------------------------------------------
-- 3. Чтобы таблица не росла вечно.
--
-- Свои строки чистит сам вызов (пункт 2), но только у того, кто пришёл
-- снова. Тот, кто дёрнул обработчик один раз и исчез, оставил бы строки
-- навсегда. Поэтому примерно каждый сотый вызов подметает всё старше
-- суток — суток, а не часа, с запасом на случай, если однажды появится
-- окно длиннее.
--
-- ПОЧЕМУ СЛУЧАЙНОСТЬ, А НЕ РАСПИСАНИЕ. pg_cron в проекте не включён, а
-- заводить его ради таблицы, которая при нашей нагрузке растёт на сотни
-- строк в день, — это обслуживать инструмент вместо задачи. Когда трафик
-- появится, эта одна строка заменяется строкой расписания, и остальная
-- функция об этом даже не узнает.

