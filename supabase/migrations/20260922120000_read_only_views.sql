-- ------------------------------------------------------------
-- 1. public_profiles: аноним мог ПИСАТЬ в profiles.
--
-- Найдено 22.09 разбором прода. Зонд: PATCH /rest/v1/public_profiles
-- анонимным ключом, без входа, — ответ 200, а не 42501. На preview
-- та же запись дошла до настоящей строки profiles.
--
-- Как так вышло — три факта, каждый по отдельности безобиден:
--
--   а) Supabase выдаёт anon и authenticated ВСЕ права (select, insert,
--      update, delete) на любой новый объект в схеме public — через
--      default privileges. Представления сюда входят.
--   б) Простое представление над одной таблицей Postgres умеет
--      обновлять сам (auto-updatable view): update и delete по нему
--      уходят в profiles.
--   в) security_invoker = false — представление работает с правами
--      ВЛАДЕЛЬЦА. Владелец profiles — postgres, а владельца таблицы RLS
--      не касается. Политика «правь только свою строку» здесь не
--      спрашивается вовсе.
--
-- И ещё хуже: триггеры-сторожа полей-прав (protect_is_creator и
-- соседи) срабатывают только при auth.role() = 'authenticated' — чтобы
-- не мешать служебному ключу. Запрос анонима они пропускают. То есть
-- посторонний без аккаунта мог выдать статус креатора (право загружать
-- карты), галочку, подпись Founder, переписать чужое имя и био — или
-- удалить профиль целиком.
--
-- ⚠️ Почему `grant select`, стоявший в каждой версии этого
-- представления, не помог: grant ДОБАВЛЯЕТ право, а не заменяет набор.
-- Всё, что выдано по умолчанию, остаётся. Это ровно правило 23.08 про
-- функции («execute роли PUBLIC выдаётся сам, снимать надо
-- специально»), только для представлений. У page_view_counts в июле его
-- соблюли — там стоит `revoke all`, — а у public_profiles нет.
--
-- Правило: конечное состояние называем свойством — «кроме чтения
-- ничего», — поэтому сначала revoke all, потом grant select.

revoke all on public.public_profiles from public, anon, authenticated;
grant select on public.public_profiles to anon, authenticated;

-- Два агрегатных представления просмотров обновлять нельзя в принципе
-- (group by), и права у них сняты ещё 20.07. Повторяем здесь, чтобы
-- правило «ни одно представление не пишется снаружи» держалось одним
-- файлом, а не памятью о трёх.
revoke all on public.page_view_counts from public, anon, authenticated;
revoke all on public.site_view_counts from public, anon, authenticated;

-- ------------------------------------------------------------
-- 2. Лента комментариев — через представление, без текста удалённых.
--
-- Политика "public read comments" (20260821180000) отдавала строку
-- целиком, включая body удалённого. В её шапке это записано решением:
-- «вырезать текст должен показ, а не выборка». Показ и вырезал —
-- rowToComment отдаёт пустую строку, — но таблица читается и мимо
-- показа: одним запросом /rest/v1/product_comments из консоли. На проде
-- 22.09 так читались четыре удалённых комментария.
--
-- Это то же правило, что с формами 20–21.08, в зеркале: там «запрет
-- ставится там, где стоит разрешение» про запись, здесь — про чтение.
-- Спрятать текст в разметке, отдавая его в выборке, — значит спрятать
-- кнопку.
--
-- Почему представление, а не права на колонки, как у profiles 15.09:
-- удалённый комментарий нужен ленте СТРОКОЙ (на его месте рисуется
-- «removed», порядок разговора сохраняется), а текст у той же колонки
-- у живых нужен, у удалённых нет. Права на колонку так не умеют — они
-- про колонку целиком. Решение «по строке» — это case.
--
-- Колонки и их имена повторяют COMMENT_COLUMNS (comment-shape.ts)
-- дословно: код переключается с таблицы на представление сменой имени
-- в from(), и больше ничем.
--
-- Удалённый — если стоит ЛЮБАЯ из двух меток. Пишутся они вместе
-- (soft_delete_comment*, /api/admin/comments), но скрывать текст по
-- одной значило бы доверять тому, что они никогда не разойдутся.

drop view if exists public.public_comments;

create view public.public_comments
with (security_invoker = false) as
  select
    id,
    product_id,
    user_id,
    case
      when deleted_by is null and deleted_at is null then body
      else ''
    end as body,
    deleted_by,
    created_at,
    updated_at
  from public.product_comments;

-- ⚠️ То же, что в разделе 1, и по той же причине: без revoke all
-- представление было бы обновляемым снаружи (id, product_id, user_id,
-- deleted_by — простые колонки) и писало бы в product_comments мимо
-- шлюза, лимитов и has_purchased.
revoke all on public.public_comments from public, anon, authenticated;
grant select on public.public_comments to anon, authenticated;

notify pgrst, 'reload schema';

