-- ⚠️ ИДЁТ ДО ДЕПЛОЯ. Файл ничего не снимает из того, чем пользуется код:
-- раздел 1 отбирает права на ЗАПИСЬ через представления (код через них
-- не пишет нигде — проверено grep'ом), раздел 2 заводит новое
-- представление, которое новый код читает сразу. Прямое чтение таблицы
-- комментариев снимает СЛЕДУЮЩАЯ миграция, 20260922130000, — после
-- деплоя.
--
