-- ============================================================
-- display_name_available(name) — свободен ли ник
--
-- Зачем отдельная функция: таблица profiles закрыта RLS так, что аноним
-- (незалогиненный посетитель на форме регистрации) не может её читать —
-- и это правильно, чужие профили наружу не отдаём. Но проверить «занят
-- ли ник» до регистрации надо. Функция security definer читает profiles
-- в обход RLS и возвращает ТОЛЬКО булево да/нет — сами ники наружу не
-- утекают, только факт занятости (это и так проверяемо на любом сайте).
--
-- Раньше уникальность ловилась только триггером handle_new_user: при
-- совпадении регистрация откатывалась с невнятной ошибкой БД. Теперь
-- форма спрашивает эту функцию заранее и показывает понятное сообщение;
-- триггер/уникальный индекс остаются вторым рубежом (защита от гонки).
--
-- Правило миграций: сначала preview, потом прод (docs/RULES.md).
-- ============================================================

create or replace function public.display_name_available(name text)
returns boolean
language sql
security definer
set search_path = ''
as $$
  select not exists (
    select 1
    from public.profiles
    where lower(display_name) = lower(name)
  );
$$;

-- Право вызвать — и анониму (форма регистрации), и залогиненному
-- (будущая смена ника в профиле).
grant execute on function public.display_name_available(text) to anon, authenticated;
