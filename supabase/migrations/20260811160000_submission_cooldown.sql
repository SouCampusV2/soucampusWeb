-- ------------------------------------------------------------
-- 1. Новые коды причин.
--
-- Ограничение на rejection_flags перечисляет допустимые значения, и без
-- расширения списка база отвергла бы отказ с новой причиной.
-- ------------------------------------------------------------
alter table public.products drop constraint if exists products_rejection_flags_check;
alter table public.products add constraint products_rejection_flags_check
  check (
    rejection_flags <@ array[
      'images', 'description', 'file', 'price', 'category', 'title',
      'stolen', 'low_effort', 'prohibited', 'spam'
    ]
  );

-- ------------------------------------------------------------
-- 2. До какого момента человеку закрыта отправка новых карт.
--
-- null — не закрыта. Дата, а не «сколько дней осталось»: счётчик надо
-- уменьшать, а дату достаточно один раз записать, и она сама
-- становится прошлым.
-- ------------------------------------------------------------
alter table public.profiles
  add column if not exists submissions_blocked_until timestamptz;

-- ------------------------------------------------------------
-- 3. Запрет в самой базе, а не в форме.
--
-- Главное требование: обойти нельзя. Проверка в /creator/upload — это
-- удобство (человек видит, до какого числа ждать), но вставка товара
-- идёт под сессией пользователя, и тот же insert отправляется из
-- консоли браузера мимо любой формы.
--
-- Поэтому условие живёт в RLS-политике вставки. Заменяем существующую
-- "creators insert own products", добавляя к ней проверку паузы —
-- отдельной политикой это сделать НЕЛЬЗЯ: несколько permissive-политик
-- на одну команду объединяются через OR, и старая продолжала бы
-- пропускать всё, что запрещает новая.
--
-- Читаем свою же строку profiles внутри политики: RLS на profiles
-- («только своя строка») этому не мешает — строка как раз своя.
--
-- Заодно политика теперь требует is_creator. Раньше не требовала: право
-- загружать проверялось только страницей /creator/upload, то есть тем
-- самым слоем, который обходится запросом мимо него. Это отдельное
-- ужесточение, но ровно того же свойства — «правило должно жить там,
-- где его нельзя обойти».
--
-- (select auth.uid()), а не auth.uid(): в этой форме Postgres вычисляет
-- значение один раз на запрос, а не на каждую строку. Так написана и
-- заменяемая политика — сохраняем.
-- ------------------------------------------------------------
drop policy if exists "creators insert own products" on public.products;

create policy "creators insert own products"
  on public.products for insert
  to authenticated
  with check (
    creator_id = (select auth.uid())
    and exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and p.is_creator
        and (
          p.submissions_blocked_until is null
          or p.submissions_blocked_until <= now()
        )
    )
  );

-- Правка уже существующей карты паузой НЕ ограничивается: политика выше
-- относится к insert, а не к update. Это осознанно — отказ, требующий
-- исправить карту, не должен сам же запрещать её исправить.
