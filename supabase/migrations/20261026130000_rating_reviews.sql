-- Оценка с отзывом — 2026-10-26.
--
-- Просьба владельца: оценка без слов ничего не объясняет; к звёздам
-- обязателен текст, и видно, кто и за что поставил — под картой и на
-- профиле автора (вкладка Reviews).
--
-- ⚠️ ИДЁТ ДО ДЕПЛОЯ — файл только ДОБАВЛЯЕТ (колонку, ограничение,
-- представление). Код переживает и обратный порядок: чтения откатываются
-- на пустой список, если представления нет. Но ЗАПИСЬ отзыва без колонки
-- откажет — поэтому миграция первой. Сначала preview, потом прод
-- (docs/RULES.md). Файл перезапускаемый.
-- ============================================================

-- ------------------------------------------------------------
-- 1. Текст отзыва.
-- ------------------------------------------------------------
alter table public.product_ratings add column if not exists body text;

-- ------------------------------------------------------------
-- 2. Текст обязателен — для НОВЫХ записей.
--
-- `not valid` — ключевое слово этой миграции. Ограничение проверяется на
-- каждой вставке и правке, но Postgres НЕ перепроверяет строки, которые
-- уже лежат в таблице. Старые оценки без текста остаются как были и
-- по-прежнему входят в средний балл; карточки отзыва у них просто нет.
-- Без `not valid` миграция упала бы на первой же старой оценке.
--
-- Правка старой оценки (смена звёзд) — это update, и ограничение её
-- проверит: поменять звёзды можно, только дописав текст. Так и задумано.
--
-- 10–1000 символов после обрезки пробелов: «ок» отзывом не считается, а
-- потолок держит объём (то же правило, что у описаний и био).
-- ⚠️ Числа повторены в src/lib/map-review-shape.ts — для подсказки в
-- форме; исполняет их эта строка.
-- ------------------------------------------------------------
alter table public.product_ratings drop constraint if exists product_ratings_body_check;
alter table public.product_ratings
  add constraint product_ratings_body_check
  check (body is not null and char_length(btrim(body)) between 10 and 1000)
  not valid;

-- ------------------------------------------------------------
-- 3. Отзывы наружу — представлением, как комментарии (public_comments).
--
-- Таблица product_ratings остаётся закрытой («read own ratings»): чужие
-- оценки без текста наружу не нужны. Представление отдаёт только
-- оценки С ТЕКСТОМ и только безопасные колонки. Читать его может
-- аноним — значит страницы карт и профилей, собираемые заранее, читают
-- отзывы без служебного ключа (а его нет в CI).
--
-- security_invoker = false — представление читает таблицу правами
-- владельца, иначе RLS «только свои» отдала бы анониму пустоту.
-- revoke all → grant select — тот же порядок, что у остальных
-- представлений (20260922120000): без revoke представление было бы
-- обновляемым снаружи.
-- ------------------------------------------------------------
drop view if exists public.public_reviews;

create view public.public_reviews
with (security_invoker = false) as
  select id, product_id, user_id, stars, body, created_at, updated_at
  from public.product_ratings
  where body is not null;

revoke all on public.public_reviews from public, anon, authenticated;
grant select on public.public_reviews to anon, authenticated;

notify pgrst, 'reload schema';

-- ------------------------------------------------------------
-- Журнал прогонов — последней строкой (docs/RULES.md → «Миграции»).
-- ------------------------------------------------------------
insert into ops.applied_migrations (version)
values ('20261026130000_rating_reviews')
on conflict (version) do nothing;
