import type { NextConfig } from "next";

// ============================================================
// Заголовки безопасности (2026-09-26, аудит перед живыми платежами —
// docs/STRIPE.md → General). До этого на проде стоял один
// Strict-Transport-Security, и его ставит сам Vercel.
//
// Четыре заголовка ниже действуют сразу: они ничего из того, чем сайт
// пользуется, не запрещают.
//
// CSP — пока ТОЛЬКО В РЕЖИМЕ ОТЧЁТА (Report-Only): браузер ничего не
// блокирует, а нарушения пишет в консоль. Так делают первым шагом
// всегда: у сайта инлайн-скрипт темы, картинки из Storage, Realtime по
// WebSocket и курсы валют в калькуляторе, и одна забытая строка в
// боевой CSP молча ломает то, что она не перечислила. Неделю-две
// смотрим консоль на preview и проде — нарушений нет, переименовываем
// заголовок в Content-Security-Policy.
//
// ⚠️ Появился новый внешний адрес (скрипт, iframe, API из браузера) —
// допиши его сюда, иначе после включения CSP он перестанет работать.
// ============================================================
const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  // 'unsafe-inline' — инлайн-скрипт темы в layout.tsx и данные, которые
  // Next вшивает в страницу. Убрать его можно только через nonce, а
  // nonce делает КАЖДУЮ страницу динамической — цена для статики
  // несоразмерна. va.vercel-scripts.com — скрипт Vercel Analytics вне
  // прода (на проде он отдаётся с нашего домена).
  "script-src 'self' 'unsafe-inline' https://va.vercel-scripts.com",
  // Инлайн-стили ставят Motion и next/font.
  "style-src 'self' 'unsafe-inline'",
  // Картинки карт и аватары — Supabase Storage; data: и blob: — превью
  // в формах загрузки до отправки.
  "img-src 'self' data: blob: https://*.supabase.co",
  "font-src 'self' data:",
  // Supabase по HTTP и Realtime по WebSocket; курсы валют в
  // калькуляторе (BuildEstimator) браузер спрашивает сам.
  "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://api.frankfurter.dev https://va.vercel-scripts.com",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  // Встраивать сайт в чужой iframe нельзя — то же, что X-Frame-Options
  // ниже; тот работает в браузерах, не знающих frame-ancestors.
  "frame-ancestors 'none'",
].join("; ");

const SECURITY_HEADERS = [
  // Браузер не угадывает тип файла по содержимому: загруженный «png»,
  // внутри которого HTML, остаётся картинкой, а не страницей.
  { key: "X-Content-Type-Options", value: "nosniff" },
  // Чужим сайтам — только наш домен, без пути: в пути бывают id сессии
  // Stripe (/marketplace/success?session_id=…) и адреса личных страниц.
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  // Защита от кликджекинга: страницу оплаты или админку нельзя
  // подложить под чужой прозрачный iframe.
  { key: "X-Frame-Options", value: "DENY" },
  // Камера, микрофон, геолокация сайту не нужны — запрещаем и себе, и
  // любому скрипту, который окажется на странице.
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), browsing-topics=()",
  },
  { key: "Content-Security-Policy-Report-Only", value: CONTENT_SECURITY_POLICY },
];

const nextConfig: NextConfig = {
  async headers() {
    return [{ source: "/:path*", headers: SECURITY_HEADERS }];
  },

  images: {
    dangerouslyAllowSVG: true,
    // Отдаём современные форматы: AVIF жмёт заметно сильнее WebP, WebP —
    // запасной для браузеров без AVIF. next/image сам выбирает по Accept.
    formats: ["image/avif", "image/webp"],

    // Загруженные пользователями картинки (обложки и галереи товаров,
    // аватары) лежат в Supabase Storage, и next/image пускает только
    // явно разрешённые хосты.
    //
    // Поддомен взят ЗВЁЗДОЧКОЙ, а не подставлен из
    // NEXT_PUBLIC_SUPABASE_URL. Сначала было именно из переменной — у
    // проекта две базы (preview и прод) с разными поддоменами, и
    // казалось правильным, чтобы конфиг сам следовал за тем, куда
    // смотрит приложение. Не сработало: next.config вычисляется на
    // отдельном этапе, и полагаться на то, что .env.local к этому
    // моменту уже разобран, нельзя — при пустой переменной список
    // молча оказывался пустым, а картинки падали с «hostname is not
    // configured». Диагностировать это тяжело: ошибка выглядит как
    // «забыли настроить», хотя настройка есть.
    //
    // Звёздочка покрывает ОБЕ базы разом и не зависит ни от какого
    // порядка загрузки. Цена — оптимизатор согласится тянуть картинку с
    // любого проекта Supabase, а не только нашего. Ограничение по
    // pathname оставляет от этого лишь публичные объекты Storage;
    // приватный бакет product-files через оптимизатор недостижим в
    // любом случае.
    remotePatterns: [
      {
        protocol: "https",
        hostname: "*.supabase.co",
        pathname: "/storage/v1/object/public/**",
      },
    ],
  },

  // Магазин переехал с /shop на /marketplace (2026-08-13, переименование
  // в «SouCampus Marketplace»). Редирект постоянный и остаётся навсегда:
  // на старые адреса ведут закладки владельца, письма Stripe с прошлых
  // покупок (success_url раньше был /shop/success), уведомления, разосланные
  // до переезда, и всё, что кто-то успел скопировать из адресной строки.
  // Стоит он ноль, а без него это 404 у человека, который уже заплатил.
  //
  // :path* захватывает и /shop/<карта>, и /shop/success, и query-строку
  // (?category=free Next переносит сам). 308, а не 307: адрес сменился
  // навсегда, и поисковику надо сказать именно это.
  async redirects() {
    return [
      { source: "/shop", destination: "/marketplace", permanent: true },
      { source: "/shop/:path*", destination: "/marketplace/:path*", permanent: true },

      // ⚠️ ЭТИ ДВЕ СТРОКИ ОБЯЗАНЫ СТОЯТЬ ВЫШЕ ПРАВИЛА ПРО ПРОФИЛЬ.
      // Next берёт ПЕРВОЕ совпавшее правило, а "/creator/:username" ниже
      // ловит и «upload» тоже — именно так форма загрузки и пропала на
      // семь дней (21–28.08): она уезжала на /@upload, то есть на
      // профиль несуществующего человека, и отдавала 404.
      //
      // Сама форма с 2026-08-28 живёт в админке (/admin/products/new,
      // разбор — в её page.tsx). Редирект остаётся навсегда и не для
      // красоты: href «/creator/upload» записан в УЖЕ РАЗОСЛАННЫЕ
      // уведомления об одобренных заявках, а строки в notifications
      // задним числом не переписать.
      //
      // Постороннему редирект ничего не открывает: /admin/* отдаёт 404
      // всем, кроме админа, — гейт стоит в layout админки.
      {
        source: "/creator/upload",
        destination: "/admin/products/new",
        permanent: true,
      },
      {
        source: "/creator/upload/submitted",
        destination: "/admin/products/new/submitted",
        permanent: true,
      },

      // Правка карты переехала в админку (2026-09-06). Пока приём
      // авторов заморожен, кабинет /resources никому не показывается, и
      // держать в нём форму значило держать дверь в комнату, которой нет
      // на плане.
      //
      // Редирект обязателен по той же причине, что и у загрузки выше:
      // «/resources/<карта>/edit» стоит в УЖЕ РАЗОСЛАННЫХ уведомлениях
      // об отклонённых картах — по этой ссылке человек идёт исправлять
      // причину отказа.
      //
      // ⚠️ Стоит ВЫШЕ правила про профиль сознательно, хотя они и не
      // пересекаются: правила читаются сверху вниз, и держать все
      // переезды одной группой дешевле, чем каждый раз вспоминать,
      // почему один оказался ниже другого.
      {
        source: "/resources/:slug/edit",
        destination: "/admin/products/:slug/edit",
        permanent: true,
      },

      // Профиль переехал с /creator/<имя> на /@<имя> (2026-08-21).
      // Прежний адрес называл РОЛЬ — а роль меняется (сегодня клиент,
      // завтра автор), профиль же остаётся тем же человеком. Тот же
      // довод и тот же приём, что у /shop выше.
      { source: "/creator/:username", destination: "/@:username", permanent: true },
    ];
  },

  // Красивый адрес профиля.
  //
  // ⚠️ ПОЧЕМУ ЧЕРЕЗ REWRITE, А НЕ ПАПКОЙ. В App Router каталог, имя
  // которого начинается с `@`, — это ИМЕНОВАННЫЙ СЛОТ параллельного
  // маршрута, а не сегмент адреса. То есть создать app/@[username] и
  // получить /@soucampus нельзя в принципе: Next поймёт это как слот
  // и не отдаст ни одной страницы.
  //
  // Поэтому страница лежит по обычному пути /u/[username], а `@` даёт
  // rewrite: адрес в браузере остаётся /@soucampus, редиректа нет,
  // лишнего перехода нет.
  //
  // Оба адреса при этом рабочие, и /u/<имя> мы просто нигде не
  // показываем. Канонический адрес проставлен в generateMetadata самой
  // страницы — этого достаточно: профили в sitemap.ts не входят.
  // Редиректом /u → /@ это лечить НЕЛЬЗЯ: редиректы выполняются раньше
  // rewrite'ов, и получилась бы бесконечная петля.
  async rewrites() {
    return [{ source: "/@:username", destination: "/u/:username" }];
  },
};

export default nextConfig;
